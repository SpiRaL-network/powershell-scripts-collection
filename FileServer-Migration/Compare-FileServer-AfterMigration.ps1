                $groups = @(foreach ($groupName in $baselineGroups) {
                    if ($fsrmGroupNameMap.ContainsKey($groupName)) { $fsrmGroupNameMap[$groupName] } else { $groupName }
                })
                $mappedTemplate = [string]$row.Template
                if ($fsrmScreenTemplateNameMap.ContainsKey($mappedTemplate)) {
                    $mappedTemplate = $fsrmScreenTemplateNameMap[$mappedTemplate]
