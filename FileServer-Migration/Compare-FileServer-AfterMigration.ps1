                        } catch { Add-Finding "FSRM" "Quota template $($row.Name)" "ERROR" "Apply failed : $_" }
                    } else {
                        $detail = if ($null -eq $cur) {
                            'Missing'
                        } else {
                            $driftDetail = @($mainDrift)
                            if ($thresholdDrift) { $driftDetail += 'threshold percentages differ' }
                            $driftDetail -join '; '
                        }
                        Add-Finding "FSRM" "Quota template $($row.Name)" "ERROR" $detail
                    }
                } else {
                    $fsrmQuotaTemplateNameMap[$row.Name] = [string]$cur.Name
                    $matchedFsrmQuotaTemplateNames[[string]$cur.Name] = $true
                    if ($localizedMatch) {
                        $currentThresholdPercentages = @($cur.Threshold | ForEach-Object { "$($_.Percentage)%" })
                        if ($builtinAliasMatch -and (([UInt64]$cur.Size -ne [UInt64]$row.Size) -or
                            ([bool]$cur.SoftLimit -ne $soft) -or
                            -not (Test-StringSetEqual $expectedThresholdPercentages $currentThresholdPercentages))) {
                            Add-Finding "FSRM" "Quota template $($row.Name)" "OK" `
                                "Known Microsoft built-in found as '$($cur.Name)'; Server 2022 definition retained"
                        } else {
                            Add-Finding "FSRM" "Quota template $($row.Name)" "OK" `
                                "Equivalent localized object found as '$($cur.Name)' (size, type and thresholds match)"
                        }
                    } else {
                        Add-Finding "FSRM" "Quota template $($row.Name)" "OK" `
                            "Present with matching size, type, description and threshold percentages"
                    }
                }
            }
            foreach ($extraQuotaTemplate in $currentFsrmQuotaTemplates) {
                if (-not $matchedFsrmQuotaTemplateNames.ContainsKey([string]$extraQuotaTemplate.Name)) {
                    Add-Finding "FSRM" "Quota template $($extraQuotaTemplate.Name)" "SKIPPED" `
                        "Present only on destination; retained because FSRM fixes never remove additional objects"
                }
            }
            if ($nativeQtValid) {
                Add-Finding "FSRM" "quota threshold actions" "OK" `
                    "Captured in native XML and used by exact-name template fixes"
            } else {
                Add-Finding "FSRM" "quota threshold actions" "WARN" `
                    "Threshold percentages are available, but action details require manual review for this legacy or incomplete export"
            }
        }

        if (Test-Path -LiteralPath $scPath -PathType Leaf) {
            $directAppliedScreenCount = 0
            Import-Csv $scPath -Encoding UTF8 | ForEach-Object {
                $row = $_
                $baselineFsrmScreenPaths[[string]$row.Path] = $true
                if (-not (ConvertTo-BoolValue $row.MatchesTemplate)) { $directAppliedScreenCount++ }
                $active = ConvertTo-BoolValue $row.Active
