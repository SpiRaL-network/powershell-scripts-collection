    }
    if ($missingLocalAccountArtifacts.Count -gt 0) {
        if ($localAccountBaselineExpected) {
            foreach ($localArtifact in $missingLocalAccountArtifacts) { Add-MissingBaseline $localArtifact 'LocalAccounts' }
        } else {
            Add-Finding "LocalAccount" "legacy export" "WARN" `
                "Local users and Administrators membership were not captured by export schemas before 2.5"
        }
    }
}
