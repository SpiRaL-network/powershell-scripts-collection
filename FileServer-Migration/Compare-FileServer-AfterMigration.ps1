# 3. SMB Share Permissions
# ---------------------------------------------------------------------------
if ($check['SharePerms']) {
    Write-Host "`n--- Checking SMB share permissions ---" -ForegroundColor White

    $currentShares = Get-SmbShare

    foreach ($s in $csvShares) {
        $expPerms = $csvPerms | Where-Object { $_.ShareName -eq $s.Name }

        $curShare = $currentShares | Where-Object { $_.Name -eq $s.Name }
        if (-not $curShare) { continue }

        $curPerms = Get-SmbShareAccess -Name $s.Name -ErrorAction SilentlyContinue

        foreach ($ep in $expPerms) {
            $expectedSid = if ($ep.PSObject.Properties.Name -contains 'AccountSid' -and -not [string]::IsNullOrWhiteSpace($ep.AccountSid)) {
                $ep.AccountSid
            } else {
                ConvertTo-IdentitySidKey $ep.AccountName
            }
            $match = $curPerms | Where-Object {
                (ConvertTo-IdentitySidKey $_.AccountName) -eq $expectedSid -and
                $_.AccessControlType -eq $ep.AccessControlType -and
                $_.AccessRight       -eq $ep.AccessRight
            }
            if (-not $match) {
                if ($fixOn['SharePerms']) {
                    try {
                        $targetAccount = ConvertTo-CurrentAccountName $expectedSid $ep.AccountName
                        if ($ep.AccessControlType -eq 'Allow') {
                            Grant-SmbShareAccess -Name $s.Name -AccountName $targetAccount `
                                -AccessRight $ep.AccessRight -Force -ErrorAction Stop | Out-Null
                        } else {
                            Block-SmbShareAccess -Name $s.Name -AccountName $targetAccount `
                                -Force -ErrorAction Stop | Out-Null
                        }
                        Add-Finding "SharePerm" "$($s.Name) / $($ep.AccountName)" "FIXED" `
                            "Permission restored : $($ep.AccessControlType) $($ep.AccessRight)"
                    } catch {
                        Add-Finding "SharePerm" "$($s.Name) / $($ep.AccountName)" "ERROR" `
                            "Restore failed : $_"
                    }
                } else {
                    Add-Finding "SharePerm" "$($s.Name) / $($ep.AccountName)" "ERROR" `
                        "Permission missing : $($ep.AccessControlType) $($ep.AccessRight)"
                }
            } else {
                Add-Finding "SharePerm" "$($s.Name) / $($ep.AccountName)" "OK" `
                    "$($ep.AccessControlType) $($ep.AccessRight)"
            }
        }

        # Re-read after optional grants/blocks, then detect every unexpected ACE.
        # Detection is read-only; no existing permission is ever removed automatically.
        $curPerms = Get-SmbShareAccess -Name $s.Name -ErrorAction SilentlyContinue
        foreach ($cp in $curPerms) {
            $currentSid = ConvertTo-IdentitySidKey $cp.AccountName
            $expected = $expPerms | Where-Object {
                $expectedEntrySid = if ($_.PSObject.Properties.Name -contains 'AccountSid' -and -not [string]::IsNullOrWhiteSpace($_.AccountSid)) {
                    $_.AccountSid
                } else {
                    ConvertTo-IdentitySidKey $_.AccountName
                }
                $expectedEntrySid -eq $currentSid -and
                $_.AccessControlType -eq $cp.AccessControlType -and
                $_.AccessRight       -eq $cp.AccessRight
            }
            if (-not $expected) {
                Add-Finding "SharePerm" "$($s.Name) / $($cp.AccountName)" "ERROR" `
                    "Unexpected permission present : $($cp.AccessControlType) $($cp.AccessRight) (not removed automatically)"
            }
        }
    }
}

# ---------------------------------------------------------------------------
# 4. NTFS ACLs (share roots)
# ---------------------------------------------------------------------------
if ($check['RootACLs']) {
    Write-Host "`n--- Checking NTFS ACLs (share roots) ---" -ForegroundColor White

    $checkedPaths = New-Object 'System.Collections.Generic.HashSet[string]' -ArgumentList ([StringComparer]::OrdinalIgnoreCase)

    foreach ($s in $csvShares) {
        $sharePath = $s.Path
        if ([string]::IsNullOrWhiteSpace($sharePath) -or $checkedPaths.Contains($sharePath)) { continue }
        [void]$checkedPaths.Add($sharePath)

        if (-not (Test-Path $sharePath -ErrorAction SilentlyContinue)) {
            Add-Finding "NTFS ACL" $sharePath "ERROR" "Path not found - disk not reattached?"
            continue
        }

        $expAcls = $csvAcls | Where-Object { $_.Path -eq $sharePath }
        if (-not $expAcls) {
            Add-Finding "NTFS ACL" $sharePath "ERROR" "No root ACL baseline for this path"
            continue
        }

        try {
            $curAcl  = Get-Acl -Path $sharePath
            $curAces = $curAcl.Access
            $expFirst = $expAcls | Select-Object -First 1
            $expOwner = $expFirst.Owner
            $expGroup = $expFirst.Group
            $expOwnerSid = if ($expFirst.PSObject.Properties.Name -contains 'OwnerSid' -and -not [string]::IsNullOrWhiteSpace($expFirst.OwnerSid)) {
                $expFirst.OwnerSid
            } else {
                ConvertTo-IdentitySidKey $expOwner
            }
            $expGroupSid = if ($expFirst.PSObject.Properties.Name -contains 'GroupSid' -and -not [string]::IsNullOrWhiteSpace($expFirst.GroupSid)) {
                $expFirst.GroupSid
            } else {
                ConvertTo-IdentitySidKey $expGroup
            }
            $curOwnerSid = ConvertTo-IdentitySidKey $curAcl.Owner
            $curGroupSid = ConvertTo-IdentitySidKey $curAcl.Group

            if ($curOwnerSid -ne $expOwnerSid) {
                Add-Finding "NTFS Owner" $sharePath "ERROR" `
                    "Owner SID mismatch - before: '$expOwner' [$expOwnerSid], after: '$($curAcl.Owner)' [$curOwnerSid]"
            }
            if ($curGroupSid -ne $expGroupSid) {
                Add-Finding "NTFS Owner" $sharePath "ERROR" `
                    "Primary group SID mismatch - before: '$expGroup' [$expGroupSid], after: '$($curAcl.Group)' [$curGroupSid]"
            }

            $expectedAceCounts = @{}
            foreach ($ea in $expAcls) {
                $expectedIdentitySid = if ($ea.PSObject.Properties.Name -contains 'IdentitySid' -and -not [string]::IsNullOrWhiteSpace($ea.IdentitySid)) {
                    $ea.IdentitySid
                } else {
                    ConvertTo-IdentitySidKey $ea.IdentityReference
                }
                $key = ('{0}|{1}|{2}|{3}|{4}|{5}' -f `
                    $expectedIdentitySid, $ea.AccessControlType, $ea.FileSystemRights,
                    $ea.IsInherited, $ea.InheritanceFlags, $ea.PropagationFlags)
                if (-not $expectedAceCounts.ContainsKey($key)) { $expectedAceCounts[$key] = 0 }
                $expectedAceCounts[$key]++
            }
            $currentAceCounts = @{}
            foreach ($ca in $curAces) {
                $key = Get-AceKey $ca
                if (-not $currentAceCounts.ContainsKey($key)) { $currentAceCounts[$key] = 0 }
                $currentAceCounts[$key]++
            }
            $allAceKeys = New-Object 'System.Collections.Generic.HashSet[string]' -ArgumentList ([StringComparer]::OrdinalIgnoreCase)
            foreach ($key in $expectedAceCounts.Keys) { [void]$allAceKeys.Add($key) }
            foreach ($key in $currentAceCounts.Keys)  { [void]$allAceKeys.Add($key) }
            $aceDrift = 0
            foreach ($key in $allAceKeys) {
                $expectedCount = if ($expectedAceCounts.ContainsKey($key)) { [int]$expectedAceCounts[$key] } else { 0 }
                $currentCount  = if ($currentAceCounts.ContainsKey($key))  { [int]$currentAceCounts[$key]  } else { 0 }
                if ($expectedCount -ne $currentCount) {
                    $aceDrift++
                    Add-Finding "NTFS ACL" $sharePath "ERROR" `
                        "ACE set differs : expected count=$expectedCount current count=$currentCount | $key"
                }
            }
            if ($aceDrift -eq 0) {
                Add-Finding "NTFS ACL" $sharePath "OK" "$($curAces.Count) ACE entries exactly match baseline"
            }

            $expProtected = $expFirst.AreAccessRulesProtected
            if ($curAcl.AreAccessRulesProtected.ToString() -ne $expProtected) {
                Add-Finding "NTFS Inheritance" $sharePath "ERROR" `
                    "Inheritance protection mismatch - before: $expProtected, after: $($curAcl.AreAccessRulesProtected)"
            }
        } catch {
            Add-Finding "NTFS ACL" $sharePath "ERROR" "Get-Acl failed : $_"
        }
    }
}

# ---------------------------------------------------------------------------
# 4b. Folder DACLs vs baseline (acls_folders_*.csv, streamed - flat memory)
# ---------------------------------------------------------------------------
if ($check['FolderACLs']) {
    $folderCsvs = @(Get-ChildItem "$ExportFolder\acls_folders_*.csv" -ErrorAction SilentlyContinue)
    if ($folderCsvs.Count -gt 0) {
        Write-Host "`n--- Checking folder DACLs vs baseline ---" -ForegroundColor White
        $fOk = 0; $fDiff = 0; $fMissing = 0; $fErr = 0; $fFixed = 0; $fSkipped = 0
        $accessOnly = [System.Security.AccessControl.AccessControlSections]::Access

        foreach ($fcsv in $folderCsvs) {
            $folderPeek = New-Object System.IO.StreamReader($fcsv.FullName)
            try {
                $folderHeader = $folderPeek.ReadLine()
                $folderFirstRow = $folderPeek.ReadLine()
            } finally {
                $folderPeek.Close()
            }
            if ($null -eq $folderHeader -or $null -eq $folderFirstRow) {
                $fErr++
                Add-Finding "FolderACL" $fcsv.Name "ERROR" "Folder ACL baseline is empty"
                continue
            }
            Import-Csv $fcsv.FullName | ForEach-Object {
                $r = $_
                if (Test-IsSystemManagedFolderPath $r.Path) {
                    $fSkipped++
                    return
                }
                $di = $null
                try { $di = New-Object System.IO.DirectoryInfo($r.Path) } catch { }
                if ($null -eq $di -or -not $di.Exists) {
                    $fMissing++
                    Add-Finding "FolderACL" $r.Path "ERROR" "Baseline folder missing on this server"
                    return
                }
                $idx = $r.Sddl.IndexOf('D:')
                if ($idx -lt 0) {
                    $fErr++
                    Add-Finding "FolderACL" $r.Path "ERROR" "Baseline row has no DACL SDDL section"
                    return
                }
                try {
                    $sec = $di.GetAccessControl('Access')
                    $baselineDacl = $r.Sddl.Substring($idx)
                    $currentDacl = $sec.GetSecurityDescriptorSddlForm('Access')
                    if ((Get-NormalizedDaclSddl $currentDacl) -eq (Get-NormalizedDaclSddl $baselineDacl)) {
                        $fOk++
                    } else {
                        if ($fixOn['FolderAcls']) {
                            try {
                                $sec.SetSecurityDescriptorSddlForm($baselineDacl, $accessOnly)
                                $di.SetAccessControl($sec)
                                $verifySec = $di.GetAccessControl('Access')
                                $verifyDacl = $verifySec.GetSecurityDescriptorSddlForm('Access')
                                if ((Get-NormalizedDaclSddl $verifyDacl) -ne (Get-NormalizedDaclSddl $baselineDacl)) {
                                    throw "DACL verification after write failed"
                                }
                                $fFixed++
                                Add-Finding "FolderACL" $r.Path "FIXED" "Drifted DACL re-applied and verified"
                            } catch {
                                $fDiff++
                                Add-Finding "FolderACL" $r.Path "ERROR" "DACL differs and fix failed : $_"
                            }
                        } else {
                            $fDiff++
                            Add-Finding "FolderACL" $r.Path "ERROR" `
                                "DACL differs from baseline (fix : Restore-FolderAcls.ps1 -PathFilter '$($r.Path)*' then -Apply, or -Fix FolderAcls)"
                        }
                    }
                } catch {
                    $fErr++
                    Add-Finding "FolderACL" $r.Path "ERROR" "DACL read/validation failed : $_"
                }
            }
        }

        if ($fDiff -eq 0 -and $fMissing -eq 0 -and $fErr -eq 0) {
            $fixedTxt = if ($fFixed -gt 0) { ", $fFixed re-applied" } else { "" }
            $skippedTxt = if ($fSkipped -gt 0) { ", $fSkipped system-managed row(s) skipped" } else { "" }
            Add-Finding "FolderACL" "all baseline rows" "OK" "$fOk folder DACLs identical to baseline$fixedTxt$skippedTxt"
        }
    } else {
        Write-Host "`n--- Folder DACL baseline not found (acls_folders_*.csv) - step skipped ---" -ForegroundColor DarkGray
    }
}

# ---------------------------------------------------------------------------
# 5. Inheritance map (streamed - flat memory, pure .NET ACL reads)
# ---------------------------------------------------------------------------
$inheritanceRows  = New-Object 'System.Collections.Generic.List[PSCustomObject]'
$inheritanceCsvOk = $false
$inhTotalChecked  = 0
$inhBrokenNow     = 0
$inhDrift         = 0
$inhOmittedOk     = 0
$inhSystemSkipped = 0

if ($check['Inheritance']) {
    Write-Host "`n--- Checking inheritance map ---" -ForegroundColor White

    $inheritanceCsvPath = "$ExportFolder\inheritance_map.csv"
    if (Test-Path $inheritanceCsvPath) {
        # Peek only (header + 1 data line) : the CSV can weigh tens of MB,
        # rows are streamed one by one below, never materialized.
        $peek = New-Object System.IO.StreamReader($inheritanceCsvPath)
        try {
            if ($null -ne $peek.ReadLine() -and $null -ne $peek.ReadLine()) { $inheritanceCsvOk = $true }
        } finally {
            $peek.Close()
        }
    }

    $inhSections = [System.Security.AccessControl.AccessControlSections]'Access, Owner'
    $sidIdType   = [System.Security.Principal.SecurityIdentifier]
    $ntIdType    = [System.Security.Principal.NTAccount]

    if ($inheritanceCsvOk) {
        # Primary strategy: stream every baseline row, re-check the ACL on that
        # path with pure .NET (Get-Acl measured ~10x slower at 100k+ rows).
        # GetAccessRules against SIDs avoids one account translation per ACE.
        # Healthy inheriting rows are counted but NOT kept for the HTML table.
        $iOk = 0; $iChanged = 0; $iMissing = 0; $iWarn = 0; $iBroken = 0
        $missingDaclFingerprint = $false
        $inhWatch = [System.Diagnostics.Stopwatch]::StartNew()
        $inhHashProvider = [System.Security.Cryptography.SHA256]::Create()

        Import-Csv $inheritanceCsvPath -Encoding UTF8 | ForEach-Object {
            $baseline = $_
            $path = $baseline.Path
            if ([string]::IsNullOrWhiteSpace($path)) { return }
            if (Test-IsSystemManagedFolderPath $path) {
                $inhSystemSkipped++
                return
            }

            $inhTotalChecked++
            if (($inhTotalChecked % 25000) -eq 0) {
                Write-Host ("    ... {0} paths re-checked ({1} sec)" -f $inhTotalChecked, [int]$inhWatch.Elapsed.TotalSeconds) -ForegroundColor DarkGray
            }

            $di = $null
            try { $di = New-Object System.IO.DirectoryInfo($path) } catch {}
            if ($null -eq $di -or -not $di.Exists) {
                $iMissing++
                Add-Finding "Inheritance" $path "ERROR" "Baseline path no longer exists on this server"
                $inheritanceRows.Add([PSCustomObject]@{
                    ShareRoot      = $baseline.ShareRoot
                    Path           = $path
                    Depth          = [int]$baseline.Depth
                    BrokenBaseline = $baseline.BrokenInheritance
                    BrokenNow      = "(missing)"
                    ExplicitACEs   = 0
                    InheritedACEs  = 0
                    Owner          = "(not found)"
                    ChangeStatus   = "MISSING"
                })
                return
            }

            try {
                $sec = $di.GetAccessControl($inhSections)
            } catch {
                $iWarn++
                Add-Finding "Inheritance" $path "ERROR" "ACL read failed : $_"
                return
            }

            $isBroken       = $sec.AreAccessRulesProtected
            $baselineBroken = ($baseline.BrokenInheritance -eq 'True')
            $expAces = 0; $inhAces = 0
            foreach ($rule in $sec.GetAccessRules($true, $true, $sidIdType)) {
                if ($rule.IsInherited) { $inhAces++ } else { $expAces++ }
            }
            if ($isBroken) { $inhBrokenNow++ }

            $changeReasons = New-Object 'System.Collections.Generic.List[string]'
            if ($isBroken -ne $baselineBroken) {
                $before = if ($baselineBroken) { "BROKEN" } else { "Active" }
                $after  = if ($isBroken)       { "BROKEN" } else { "Active" }
                $changeReasons.Add("inheritance before=$before after=$after")
            }
            if ([int]$baseline.ExplicitACECount -ne $expAces) {
                $changeReasons.Add("explicit ACEs before=$($baseline.ExplicitACECount) after=$expAces")
            }
            if ([int]$baseline.InheritedACECount -ne $inhAces) {
                $changeReasons.Add("inherited ACEs before=$($baseline.InheritedACECount) after=$inhAces")
            }
            if ($baseline.PSObject.Properties.Name -contains 'DaclSha256' -and -not [string]::IsNullOrWhiteSpace($baseline.DaclSha256)) {
                $currentDaclHash = Get-Sha256Hex (Get-NormalizedDaclSddl $sec.GetSecurityDescriptorSddlForm('Access')) $inhHashProvider
                if ($currentDaclHash -ne $baseline.DaclSha256) {
                    $changeReasons.Add("DACL fingerprint differs")
                }
            } elseif (-not $missingDaclFingerprint) {
                $missingDaclFingerprint = $true
                $iWarn++
                Add-Finding "Inheritance" "DaclSha256" "ERROR" `
                    "Legacy inheritance baseline has no DACL fingerprint - exact deep ACL equality cannot be proven"
            }

            if ($changeReasons.Count -gt 0) {
                Add-Finding "Inheritance" $path "ERROR" ("ACL/inheritance changed : {0}" -f ($changeReasons -join '; '))
                $iChanged++
                $changeStatus = "CHANGED"
            } else {
                $iOk++
                if ($baselineBroken) { $iBroken++ }
                $changeStatus = "OK"
            }

            if ($changeStatus -eq "CHANGED" -or $isBroken -or $baselineBroken) {
                $ownerTxt = "(unknown)"
                try { $ownerTxt = $sec.GetOwner($ntIdType).Value } catch {
                    try { $ownerTxt = $sec.GetOwner($sidIdType).Value } catch {}
                }
                $inheritanceRows.Add([PSCustomObject]@{
                    ShareRoot      = $baseline.ShareRoot
                    Path           = $path
                    Depth          = [int]$baseline.Depth
                    BrokenBaseline = $baseline.BrokenInheritance
                    BrokenNow      = $isBroken.ToString()
                    ExplicitACEs   = $expAces
                    InheritedACEs  = $inhAces
                    Owner          = $ownerTxt
                    ChangeStatus   = $changeStatus
                })
            } else {
                $inhOmittedOk++
            }
        }

        $inhHashProvider.Dispose()
        $inhWatch.Stop()
        $inhDrift = $iChanged + $iMissing + $iWarn
        Write-Host ("    {0} paths re-checked in {1} sec" -f $inhTotalChecked, [int]$inhWatch.Elapsed.TotalSeconds) -ForegroundColor DarkGray

        if ($iChanged -eq 0 -and $iMissing -eq 0 -and $iWarn -eq 0) {
            $inhSkippedTxt = if ($inhSystemSkipped -gt 0) { ", $inhSystemSkipped system-managed row(s) skipped" } else { "" }
            Add-Finding "Inheritance" "all baseline rows" "OK" `
                "$iOk paths re-checked vs baseline, ACL counts and inheritance state identical ($iBroken broken as expected)$inhSkippedTxt"
        }
    } else {
        # No baseline: BFS from share roots + semantic check only
        Add-Finding "Inheritance" "inheritance_map.csv" "ERROR" `
            "Baseline CSV missing or empty - semantic checks cannot prove migration equality"

        $scannedInhRoots = New-Object 'System.Collections.Generic.HashSet[string]' -ArgumentList ([StringComparer]::OrdinalIgnoreCase)
        $inhRoots = New-Object 'System.Collections.Generic.List[string]'
        $candidateInhRoots = New-Object 'System.Collections.Generic.HashSet[string]' -ArgumentList ([StringComparer]::OrdinalIgnoreCase)
        if ($csvShares) {
            foreach ($s in $csvShares) {
                if (-not [string]::IsNullOrWhiteSpace($s.Path)) { [void]$candidateInhRoots.Add($s.Path) }
            }
        }
        if ($csvAcls) {
            foreach ($a in $csvAcls) {
                if (-not [string]::IsNullOrWhiteSpace($a.Path)) { [void]$candidateInhRoots.Add($a.Path) }
            }
        }
        $fallbackFolderCsvs = @(Get-ChildItem "$ExportFolder\acls_folders_*.csv" -ErrorAction SilentlyContinue)
        foreach ($fcsv in $fallbackFolderCsvs) {
            $firstRow = Import-Csv $fcsv.FullName -Encoding UTF8 | Select-Object -First 1
            if ($null -ne $firstRow -and -not [string]::IsNullOrWhiteSpace($firstRow.ShareRoot)) {
                [void]$candidateInhRoots.Add($firstRow.ShareRoot)
            }
        }
        foreach ($root in $candidateInhRoots) { [void]$inhRoots.Add($root) }

        foreach ($root in $inhRoots) {
            if ($scannedInhRoots.Contains($root)) { continue }
            $rootDi = $null
            try { $rootDi = New-Object System.IO.DirectoryInfo($root) } catch { }
            if ($null -eq $rootDi -or -not $rootDi.Exists) { continue }
            [void]$scannedInhRoots.Add($root)

            Get-DirsBFS -Root $root -MaxDepth $InheritanceCheckDepth | ForEach-Object {
                $dir = $_
                $di = $null
                try { $di = New-Object System.IO.DirectoryInfo($dir.Path) } catch {}
                if ($null -eq $di) { return }
                try { $sec = $di.GetAccessControl($inhSections) } catch { return }

                $inhTotalChecked++
                $isBroken = $sec.AreAccessRulesProtected
                if (-not $isBroken) {
                    $inhOmittedOk++
                    return
                }
                $inhBrokenNow++

                $expAces = 0; $inhAces = 0
                foreach ($rule in $sec.GetAccessRules($true, $true, $sidIdType)) {
                    if ($rule.IsInherited) { $inhAces++ } else { $expAces++ }
                }

                if ($dir.Depth -ge 1) {
                    Add-Finding "Inheritance" $dir.Path "WARN" `
                        ("Sub-folder depth={0} has broken inheritance (expected to inherit from root)" -f $dir.Depth)
                }

                $ownerTxt = "(unknown)"
                try { $ownerTxt = $sec.GetOwner($ntIdType).Value } catch {
                    try { $ownerTxt = $sec.GetOwner($sidIdType).Value } catch {}
                }
                $inheritanceRows.Add([PSCustomObject]@{
                    ShareRoot      = $root
                    Path           = $dir.Path
                    Depth          = $dir.Depth
                    BrokenBaseline = "N/A"
                    BrokenNow      = $isBroken.ToString()
                    ExplicitACEs   = $expAces
                    InheritedACEs  = $inhAces
                    Owner          = $ownerTxt
                    ChangeStatus   = "N/A"
                })
            }
        }
    }
}

# ---------------------------------------------------------------------------
# 6. FSRM (idempotent, no removal; native XML notifications in schema 2.4)
# ---------------------------------------------------------------------------
if ($check['FSRM']) {
    Write-Host "`n--- Checking FSRM configuration ---" -ForegroundColor White
    if (-not (Get-Module -ListAvailable -Name FileServerResourceManager)) {
        Add-Finding "FSRM" "FileServerResourceManager" "ERROR" `
            "FSRM module is not installed (Install-WindowsFeature FS-Resource-Manager -IncludeManagementTools)"
    } else {
        Import-Module FileServerResourceManager -ErrorAction SilentlyContinue
        $fgPath = Join-Path $ExportFolder 'fsrm_filegroups.csv'
        $stPath = Join-Path $ExportFolder 'fsrm_screen_templates.csv'
        $scPath = Join-Path $ExportFolder 'fsrm_screens_applied.csv'
        $qtPath = Join-Path $ExportFolder 'fsrm_quota_templates.csv'
        $qaPath = Join-Path $ExportFolder 'fsrm_quotas_applied.csv'
        $nativeFgPath = Join-Path $ExportFolder 'fsrm_filegroups.xml'
        $nativeStPath = Join-Path $ExportFolder 'fsrm_screen_templates.xml'
        $nativeQtPath = Join-Path $ExportFolder 'fsrm_quota_templates.xml'
        $nativeFsrmDeclaredComplete = ($null -ne $exportMetadata -and
            $exportMetadata.PSObject.Properties.Name -contains 'FsrmNativeExport' -and
            [string]$exportMetadata.FsrmNativeExport -eq 'Complete')
        $nativeFgValid = ($nativeFsrmDeclaredComplete -and (Test-XmlFileWellFormed $nativeFgPath))
        $nativeStValid = ($nativeFsrmDeclaredComplete -and (Test-XmlFileWellFormed $nativeStPath))
        $nativeQtValid = ($nativeFsrmDeclaredComplete -and (Test-XmlFileWellFormed $nativeQtPath))
        if ($nativeFsrmDeclaredComplete -and -not ($nativeFgValid -and $nativeStValid -and $nativeQtValid)) {
            Add-Finding "FSRM" "native XML baseline" "ERROR" `
                "Export metadata declares a complete native baseline, but at least one XML file is missing or invalid"
        } elseif ($nativeFgValid -and $nativeStValid -and $nativeQtValid) {
            Add-Finding "FSRM" "native XML baseline" "OK" `
                "File groups and templates include complete native settings and notification actions"
        }
        $currentFsrmGroups = @(Get-FsrmFileGroup -ErrorAction SilentlyContinue)
        $currentFsrmScreenTemplates = @(Get-FsrmFileScreenTemplate -ErrorAction SilentlyContinue)
        $currentFsrmQuotaTemplates = @(Get-FsrmQuotaTemplate -ErrorAction SilentlyContinue)
        $fsrmGroupNameMap = @{}
        $fsrmScreenTemplateNameMap = @{}
        $fsrmQuotaTemplateNameMap = @{}
        $matchedFsrmGroupNames = @{}
        $matchedFsrmScreenTemplateNames = @{}
        $matchedFsrmQuotaTemplateNames = @{}
        $baselineFsrmScreenPaths = @{}
        $baselineFsrmQuotaPaths = @{}

        if (Test-Path -LiteralPath $fgPath -PathType Leaf) {
            Import-Csv $fgPath -Encoding UTF8 | ForEach-Object {
                $row = $_
                $expectedInclude = @(ConvertFrom-SemicolonList $row.IncludePattern)
                $expectedExclude = @(ConvertFrom-SemicolonList $row.ExcludePattern)
                $cur = $currentFsrmGroups | Where-Object { $_.Name -ieq $row.Name } | Select-Object -First 1
                $localizedMatch = $false
                $builtinAliasMatch = $false
                if ($null -eq $cur) {
                    $builtinEnglishName = Get-FsrmBuiltinEnglishName -ObjectType FileGroup -Name $row.Name
                    if (-not [string]::IsNullOrWhiteSpace($builtinEnglishName)) {
                        $cur = $currentFsrmGroups | Where-Object { $_.Name -ieq $builtinEnglishName } | Select-Object -First 1
                        if ($null -ne $cur) {
                            $localizedMatch = $true
                            $builtinAliasMatch = $true
                        }
                    }
                }
                if ($null -eq $cur) {
                    $semanticMatches = @($currentFsrmGroups | Where-Object {
                        (Test-StringSetEqual $expectedInclude @($_.IncludePattern)) -and
                        (Test-StringSetEqual $expectedExclude @($_.ExcludePattern))
                    })
                    if ($semanticMatches.Count -eq 1) {
                        $cur = $semanticMatches[0]
                        $localizedMatch = $true
                    } elseif ($semanticMatches.Count -gt 1) {
                        Add-Finding "FSRM" "File group $($row.Name)" "ERROR" `
                            "Name is localized and semantic match is ambiguous; no automatic fix"
                        return
                    }
                }
                if ($null -eq $cur) {
                    if ($fixOn['Fsrm']) {
                        try {
                            if ($nativeFgValid) {
                                Invoke-FsrmNativeImport -CommandName 'filescrn.exe' -ObjectType 'filegroup' `
                                    -SelectionName 'filegroup' -SelectionValue $row.Name -XmlPath $nativeFgPath
                                if ($null -eq (Get-FsrmFileGroup -Name $row.Name -ErrorAction SilentlyContinue)) {
                                    throw 'native import completed but the file group is still missing'
                                }
                                $detail = 'Imported from native XML'
                            } else {
                                New-FsrmFileGroup -Name $row.Name -IncludePattern $expectedInclude `
                                    -ExcludePattern $expectedExclude -ErrorAction Stop | Out-Null
                                $detail = 'Created from baseline CSV'
                            }
                            $verifyGroup = Get-FsrmFileGroup -Name $row.Name -ErrorAction Stop
                            $verifyGroupDrift = @(Get-FsrmFileGroupDrift $verifyGroup $expectedInclude $expectedExclude)
                            if ($verifyGroupDrift.Count -gt 0) {
                                throw "post-fix verification failed : $($verifyGroupDrift -join '; ')"
                            }
                            $fsrmGroupNameMap[$row.Name] = $row.Name
                            $matchedFsrmGroupNames[$row.Name] = $true
                            Add-Finding "FSRM" "File group $($row.Name)" "FIXED" "$detail; verified"
                        } catch { Add-Finding "FSRM" "File group $($row.Name)" "ERROR" "Create failed : $_" }
                    } else { Add-Finding "FSRM" "File group $($row.Name)" "ERROR" "Missing" }
                } else {
                    $fsrmGroupNameMap[$row.Name] = [string]$cur.Name
                    $matchedFsrmGroupNames[[string]$cur.Name] = $true
                    if ($localizedMatch) {
                        if ($builtinAliasMatch -and
                            (-not (Test-StringSetEqual $expectedInclude @($cur.IncludePattern)) -or
                             -not (Test-StringSetEqual $expectedExclude @($cur.ExcludePattern)))) {
                            Add-Finding "FSRM" "File group $($row.Name)" "OK" `
                                "Known Microsoft built-in found as '$($cur.Name)'; Server 2022 pattern definition retained"
                        } else {
                            Add-Finding "FSRM" "File group $($row.Name)" "OK" `
                                "Equivalent localized object found as '$($cur.Name)' (patterns match)"
                        }
                    } elseif (-not (Test-StringSetEqual $expectedInclude @($cur.IncludePattern)) -or
                          -not (Test-StringSetEqual $expectedExclude @($cur.ExcludePattern))) {
                        if ($fixOn['Fsrm']) {
                            try {
                                if ($nativeFgValid) {
                                    Invoke-FsrmNativeImport -CommandName 'filescrn.exe' -ObjectType 'filegroup' `
                                        -SelectionName 'filegroup' -SelectionValue $row.Name -XmlPath $nativeFgPath
                                    $detail = 'Restored from native XML'
                                } else {
                                    Set-FsrmFileGroup -Name $row.Name -IncludePattern $expectedInclude `
                                        -ExcludePattern $expectedExclude -ErrorAction Stop | Out-Null
                                    $detail = 'Patterns synchronized from CSV baseline'
                                }
                                $verifyGroup = Get-FsrmFileGroup -Name $row.Name -ErrorAction Stop
                                $verifyGroupDrift = @(Get-FsrmFileGroupDrift $verifyGroup $expectedInclude $expectedExclude)
                                if ($verifyGroupDrift.Count -gt 0) {
                                    throw "post-fix verification failed : $($verifyGroupDrift -join '; ')"
                                }
                                Add-Finding "FSRM" "File group $($row.Name)" "FIXED" "$detail; verified"
                            } catch { Add-Finding "FSRM" "File group $($row.Name)" "ERROR" "Update failed : $_" }
                        } else { Add-Finding "FSRM" "File group $($row.Name)" "ERROR" "Patterns differ" }
                    } else {
                        Add-Finding "FSRM" "File group $($row.Name)" "OK" "Present and patterns match"
                    }
                }
            }
            foreach ($extraFsrmGroup in $currentFsrmGroups) {
                if (-not $matchedFsrmGroupNames.ContainsKey([string]$extraFsrmGroup.Name)) {
                    Add-Finding "FSRM" "File group $($extraFsrmGroup.Name)" "SKIPPED" `
                        "Present only on destination; retained because FSRM fixes never remove additional objects"
                }
            }
        }

        if (Test-Path -LiteralPath $stPath -PathType Leaf) {
            Import-Csv $stPath -Encoding UTF8 | ForEach-Object {
                $row = $_
                $baselineGroups = @(ConvertFrom-SemicolonList $row.IncludeGroup)
                $groups = @(foreach ($groupName in $baselineGroups) {
                    if ($fsrmGroupNameMap.ContainsKey($groupName)) { $fsrmGroupNameMap[$groupName] } else { $groupName }
                })
                $nativeScreenImportSafe = $nativeStValid
                foreach ($groupName in $baselineGroups) {
                    if ($fsrmGroupNameMap.ContainsKey($groupName) -and
                        [string]$fsrmGroupNameMap[$groupName] -ine [string]$groupName) {
                        $nativeScreenImportSafe = $false
                    }
                }
                $active = ConvertTo-BoolValue $row.Active
                $cur = $currentFsrmScreenTemplates | Where-Object { $_.Name -ieq $row.Name } | Select-Object -First 1
                $localizedMatch = $false
                $builtinAliasMatch = $false
                if ($null -eq $cur) {
                    $builtinEnglishName = Get-FsrmBuiltinEnglishName -ObjectType ScreenTemplate -Name $row.Name
                    if (-not [string]::IsNullOrWhiteSpace($builtinEnglishName)) {
                        $cur = $currentFsrmScreenTemplates | Where-Object { $_.Name -ieq $builtinEnglishName } | Select-Object -First 1
                        if ($null -ne $cur) {
                            $localizedMatch = $true
                            $builtinAliasMatch = $true
                        }
                    }
                }
                if ($null -eq $cur) {
                    $semanticMatches = @($currentFsrmScreenTemplates | Where-Object {
                        ([bool]$_.Active -eq $active) -and
                        (Test-StringSetEqual $groups @($_.IncludeGroup))
                    })
                    if ($semanticMatches.Count -eq 1) {
                        $cur = $semanticMatches[0]
                        $localizedMatch = $true
                    } elseif ($semanticMatches.Count -gt 1) {
                        Add-Finding "FSRM" "Screen template $($row.Name)" "ERROR" `
                            "Name is localized and semantic match is ambiguous; no automatic fix"
                        return
                    }
                }
                $drift = ($null -ne $cur -and -not $localizedMatch -and (([bool]$cur.Active -ne $active) -or
                    ([string]$cur.Description -ne [string]$row.Description) -or
                    -not (Test-StringSetEqual $groups @($cur.IncludeGroup))))
                if ($null -eq $cur -or $drift) {
                    if ($fixOn['Fsrm']) {
                        try {
                            if ($nativeScreenImportSafe) {
                                Invoke-FsrmNativeImport -CommandName 'filescrn.exe' -ObjectType 'template' `
                                    -SelectionName 'template' -SelectionValue $row.Name -XmlPath $nativeStPath
                                if ($null -eq (Get-FsrmFileScreenTemplate -Name $row.Name -ErrorAction SilentlyContinue)) {
                                    throw 'native import completed but the screen template is still missing'
                                }
                                $detail = 'Restored from native XML; notification actions preserved'
                            } elseif ($null -eq $cur) {
                                New-FsrmFileScreenTemplate -Name $row.Name -Description $row.Description `
                                    -IncludeGroup $groups -Active:$active -ErrorAction Stop | Out-Null
                                $detail = 'Created from baseline CSV; notification actions require manual review'
                            } else {
                                Set-FsrmFileScreenTemplate -Name $row.Name -Description $row.Description `
                                    -IncludeGroup $groups -Active:$active -ErrorAction Stop | Out-Null
                                $detail = 'Main properties synchronized from CSV; existing notification actions preserved'
                            }
                            $verifyScreenTemplate = Get-FsrmFileScreenTemplate -Name $row.Name -ErrorAction Stop
                            $verifyScreenTemplateDrift = @(Get-FsrmScreenTemplateDrift $verifyScreenTemplate $row $groups)
                            if ($verifyScreenTemplateDrift.Count -gt 0) {
                                throw "post-fix verification failed : $($verifyScreenTemplateDrift -join '; ')"
                            }
                            $fsrmScreenTemplateNameMap[$row.Name] = $row.Name
                            $matchedFsrmScreenTemplateNames[$row.Name] = $true
                            Add-Finding "FSRM" "Screen template $($row.Name)" "FIXED" "$detail; verified"
                        } catch { Add-Finding "FSRM" "Screen template $($row.Name)" "ERROR" "Apply failed : $_" }
                    } else {
                        $detail = if ($null -eq $cur) { 'Missing' } else { 'Main properties differ' }
                        Add-Finding "FSRM" "Screen template $($row.Name)" "ERROR" $detail
                    }
                } else {
                    $fsrmScreenTemplateNameMap[$row.Name] = [string]$cur.Name
                    $matchedFsrmScreenTemplateNames[[string]$cur.Name] = $true
                    if ($localizedMatch) {
                        if ($builtinAliasMatch -and (([bool]$cur.Active -ne $active) -or
                            -not (Test-StringSetEqual $groups @($cur.IncludeGroup)))) {
                            Add-Finding "FSRM" "Screen template $($row.Name)" "OK" `
                                "Known Microsoft built-in found as '$($cur.Name)'; Server 2022 definition retained"
                        } else {
                            Add-Finding "FSRM" "Screen template $($row.Name)" "OK" `
                                "Equivalent localized object found as '$($cur.Name)' (active mode and file groups match)"
                        }
                    } else {
                        Add-Finding "FSRM" "Screen template $($row.Name)" "OK" `
                            "Present with matching description, active mode and file groups"
                    }
                }
            }
            foreach ($extraScreenTemplate in $currentFsrmScreenTemplates) {
                if (-not $matchedFsrmScreenTemplateNames.ContainsKey([string]$extraScreenTemplate.Name)) {
                    Add-Finding "FSRM" "Screen template $($extraScreenTemplate.Name)" "SKIPPED" `
                        "Present only on destination; retained because FSRM fixes never remove additional objects"
                }
            }
            if ($nativeStValid) {
                Add-Finding "FSRM" "screen template notifications" "OK" `
                    "Captured in native XML and used by exact-name template fixes"
            } else {
                Add-Finding "FSRM" "screen template notifications" "WARN" `
                    "Notification actions were not captured by this legacy or incomplete export and require manual review"
            }
        }

        if (Test-Path -LiteralPath $qtPath -PathType Leaf) {
            Import-Csv $qtPath -Encoding UTF8 | ForEach-Object {
                $row = $_
                $soft = ConvertTo-BoolValue $row.SoftLimit
                $expectedThresholdPercentages = @(ConvertFrom-SemicolonList $row.Threshold)
                $cur = $currentFsrmQuotaTemplates | Where-Object { $_.Name -ieq $row.Name } | Select-Object -First 1
                $localizedMatch = $false
                $builtinAliasMatch = $false
                if ($null -eq $cur) {
                    $builtinEnglishName = Get-FsrmBuiltinEnglishName -ObjectType QuotaTemplate -Name $row.Name
                    if (-not [string]::IsNullOrWhiteSpace($builtinEnglishName)) {
                        $cur = $currentFsrmQuotaTemplates | Where-Object { $_.Name -ieq $builtinEnglishName } | Select-Object -First 1
                        if ($null -ne $cur) {
                            $localizedMatch = $true
                            $builtinAliasMatch = $true
                        }
                    }
                }
                if ($null -eq $cur) {
                    $semanticMatches = @($currentFsrmQuotaTemplates | Where-Object {
                        $currentThresholdPercentages = @($_.Threshold | ForEach-Object { "$($_.Percentage)%" })
                        ([UInt64]$_.Size -eq [UInt64]$row.Size) -and
                        ([bool]$_.SoftLimit -eq $soft) -and
                        (Test-StringSetEqual $expectedThresholdPercentages $currentThresholdPercentages)
                    })
                    if ($semanticMatches.Count -eq 1) {
                        $cur = $semanticMatches[0]
                        $localizedMatch = $true
                    } elseif ($semanticMatches.Count -gt 1) {
                        Add-Finding "FSRM" "Quota template $($row.Name)" "ERROR" `
                            "Name is localized and semantic match is ambiguous; no automatic fix"
                        return
                    }
                }
                $mainDrift = @()
                $thresholdDrift = $false
                if ($null -ne $cur -and -not $localizedMatch) {
                    $mainDrift = @(Get-FsrmQuotaTemplateMainDrift $cur $row)
                    $thresholdDrift = -not (Test-FsrmQuotaThresholdsMatch $cur $expectedThresholdPercentages)
                }
                if ($null -ne $cur -and -not $localizedMatch -and $thresholdDrift -and -not $nativeQtValid) {
                    $fsrmQuotaTemplateNameMap[$row.Name] = [string]$cur.Name
                    $matchedFsrmQuotaTemplateNames[[string]$cur.Name] = $true
                    Add-Finding "FSRM" "Quota template $($row.Name)" "ERROR" `
                        "Threshold percentages differ; legacy CSV cannot safely replace thresholds without losing notification actions"
                    return
                }
                if ($null -eq $cur -or $mainDrift.Count -gt 0 -or $thresholdDrift) {
                    if ($fixOn['Fsrm']) {
                        try {
                            if ($nativeQtValid) {
                                Invoke-FsrmNativeImport -CommandName 'dirquota.exe' -ObjectType 'template' `
                                    -SelectionName 'template' -SelectionValue $row.Name -XmlPath $nativeQtPath
                                if ($null -eq (Get-FsrmQuotaTemplate -Name $row.Name -ErrorAction SilentlyContinue)) {
                                    throw 'native import completed but the quota template is still missing'
                                }
                                $detail = 'Restored from native XML; threshold actions preserved'
                            } else {
                                $thresholds = @()
                                foreach ($value in (ConvertFrom-SemicolonList $row.Threshold)) {
                                    if ($value -match '^(\d+)%$') {
                                        $thresholds += New-FsrmQuotaThreshold -Percentage ([UInt32]$matches[1])
                                    }
                                }
                                $params = @{ Name=$row.Name; Description=$row.Description; Size=[UInt64]$row.Size;
                                    SoftLimit=$soft; ErrorAction='Stop' }
                                if ($null -eq $cur) {
                                    if ($thresholds.Count -gt 0) { $params['Threshold'] = $thresholds }
                                    New-FsrmQuotaTemplate @params | Out-Null
                                    $detail='Created from baseline CSV; threshold actions require manual review'
                                } else {
                                    # Legacy CSV has percentages but not action details.
                                    # Do not replace thresholds and remove current actions.
                                    Set-FsrmQuotaTemplate @params | Out-Null
                                    $detail='Main properties synchronized from CSV; existing threshold actions preserved'
                                }
                            }
                            $verifyQuotaTemplate = Get-FsrmQuotaTemplate -Name $row.Name -ErrorAction Stop
                            $verifyQuotaTemplateDrift = @(Get-FsrmQuotaTemplateMainDrift $verifyQuotaTemplate $row)
                            if ($verifyQuotaTemplateDrift.Count -gt 0 -or
                                -not (Test-FsrmQuotaThresholdsMatch $verifyQuotaTemplate $expectedThresholdPercentages)) {
                                $verifyDetail = @($verifyQuotaTemplateDrift)
                                if (-not (Test-FsrmQuotaThresholdsMatch $verifyQuotaTemplate $expectedThresholdPercentages)) {
                                    $verifyDetail += 'threshold percentages differ'
                                }
                                throw "post-fix verification failed : $($verifyDetail -join '; ')"
                            }
                            $fsrmQuotaTemplateNameMap[$row.Name] = $row.Name
                            $matchedFsrmQuotaTemplateNames[$row.Name] = $true
