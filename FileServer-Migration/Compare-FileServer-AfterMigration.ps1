function Test-IsGeneratedUserTask {
    param($TaskRow)
    if ($TaskRow.TaskName -like 'Optimize Start Menu Cache Files-S-1-5-21-*') { return $true }
    if ($TaskRow.TaskPath -ieq '\WPD\' -and $TaskRow.TaskName -like 'SqmUpload_S-1-5-21-*') { return $true }
