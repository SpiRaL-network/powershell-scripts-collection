$findings = New-Object 'System.Collections.Generic.List[PSCustomObject]'

function Add-Finding {
    param(
        [string]$Category,
        [string]$Item,
        [ValidateSet('OK','WARN','ERROR','FIXED','SKIPPED')]
        [string]$Status,
        [string]$Detail
    )
    $findings.Add([PSCustomObject]@{
        Time     = (Get-Date -Format "HH:mm:ss")
        Category = $Category
        Item     = $Item
        Status   = $Status
        Detail   = $Detail
    })
    $color = switch ($Status) {
        'OK'    { 'Green'  }
        'WARN'  { 'Yellow' }
        'ERROR' { 'Red'    }
        'FIXED' { 'Cyan'   }
        'SKIPPED' { 'DarkGray' }
    }
    Write-Host ("[{0}] [{1}] {2} : {3}" -f (Get-Date -Format "HH:mm:ss"), $Status, $Item, $Detail) -ForegroundColor $color
}

