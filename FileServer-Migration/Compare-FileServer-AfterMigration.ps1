if ($check['Volumes']) {
    Write-Host "`n--- Checking volumes ---" -ForegroundColor White
    if ($null -ne $csvVolumes -and $null -ne $csvDisks) {
        try {
            $currentStorage = Get-StorageInventory
            $baselineDataVolumes = @($csvVolumes | Where-Object { ConvertTo-BoolValue $_.IsDataDisk })
            $matchedVolumeKeys = New-Object 'System.Collections.Generic.HashSet[string]' -ArgumentList ([StringComparer]::OrdinalIgnoreCase)

            foreach ($baselineVolume in $baselineDataVolumes) {
                $expectedLetter = [string](Get-OptionalPropertyValue $baselineVolume 'DriveLetter')
                $itemName = if ([string]::IsNullOrWhiteSpace($expectedLetter)) {
                    [string](Get-OptionalPropertyValue $baselineVolume 'FileSystemLabel' '(no letter)')
                } else { "$expectedLetter`:" }
                $match = Get-StableVolumeMatch $baselineVolume $currentStorage.Volumes
                if ($null -eq $match) {
                    Add-Finding 'Volume' $itemName 'ERROR' ("Migrated volume missing (label='{0}', size={1})" -f `
                        (Get-OptionalPropertyValue $baselineVolume 'FileSystemLabel'),
                        (Get-OptionalPropertyValue $baselineVolume 'Size'))
                    continue
                }

                $currentVolume = $match.Volume
                [void]$matchedVolumeKeys.Add(("{0}|{1}|{2}" -f `
                    (Get-OptionalPropertyValue $currentVolume 'VolumeUniqueId'),
                    (Get-OptionalPropertyValue $currentVolume 'DiskNumber'),
                    (Get-OptionalPropertyValue $currentVolume 'PartitionNumber')))
                $currentLetter = [string](Get-OptionalPropertyValue $currentVolume 'DriveLetter')
                if ($match.Stable -and $currentLetter -ine $expectedLetter) {
                    $currentDisplay = if ([string]::IsNullOrWhiteSpace($currentLetter)) { '(none)' } else { "$currentLetter`:" }
                    Add-Finding 'Volume' $itemName 'ERROR' ("Stable volume found by {0}, but drive letter is {1}" -f $match.Method, $currentDisplay)
                } elseif (-not $match.Stable) {
                    Add-Finding 'Volume' $itemName 'WARN' 'Legacy mapping used drive letter only; re-export with schema 2.5 for stable disk identity validation'
                }

                $expectedSize = [string](Get-OptionalPropertyValue $baselineVolume 'Size')
                $currentSize = Get-OptionalPropertyValue $currentVolume 'Size' 0
                if (-not [string]::IsNullOrWhiteSpace($expectedSize) -and
                    -not (Test-StorageSizeMatch $expectedSize $currentSize)) {
                    Add-Finding 'Volume' $itemName 'ERROR' ("Size differs: before={0}, after={1} bytes" -f $expectedSize, $currentSize)
                }
                $expectedFileSystem = [string](Get-OptionalPropertyValue $baselineVolume 'FileSystem')
                $currentFileSystem = [string](Get-OptionalPropertyValue $currentVolume 'FileSystem')
                if (-not [string]::IsNullOrWhiteSpace($expectedFileSystem) -and $currentFileSystem -ine $expectedFileSystem) {
                    Add-Finding 'Volume' $itemName 'ERROR' ("File system differs: before='{0}', after='{1}'" -f $expectedFileSystem, $currentFileSystem)
                }
                $expectedLabel = [string](Get-OptionalPropertyValue $baselineVolume 'FileSystemLabel')
                $currentLabel = [string](Get-OptionalPropertyValue $currentVolume 'FileSystemLabel')
                if ($currentLabel -ine $expectedLabel) {
                    Add-Finding 'Volume' $itemName 'WARN' ("Label differs: before='{0}', after='{1}'" -f $expectedLabel, $currentLabel)
                }
                $health = [string](Get-OptionalPropertyValue $currentVolume 'HealthStatus')
                if (-not [string]::IsNullOrWhiteSpace($health) -and $health -ine 'Healthy') {
                    Add-Finding 'Volume' $itemName 'WARN' "Current health status is '$health'"
                }
                if ($match.Stable -and $currentLetter -ieq $expectedLetter -and
                    (Test-StorageSizeMatch $expectedSize $currentSize) -and
                    ([string]::IsNullOrWhiteSpace($expectedFileSystem) -or $currentFileSystem -ieq $expectedFileSystem)) {
                    Add-Finding 'Volume' $itemName 'OK' ("Stable mapping verified by {0} (disk {1}, partition {2})" -f `
                        $match.Method, (Get-OptionalPropertyValue $currentVolume 'DiskNumber'),
                        (Get-OptionalPropertyValue $currentVolume 'PartitionNumber'))
                }
            }

            $dataDiskNumbers = @($baselineDataVolumes | ForEach-Object {
                [string](Get-OptionalPropertyValue $_ 'DiskNumber')
            } | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Select-Object -Unique)
            if ($dataDiskNumbers.Count -eq 0) {
                Add-Finding 'Volume' 'disk identity' 'WARN' 'Legacy export has no data disk mapping; disk identity check skipped'
            }
            foreach ($dataDiskNumber in $dataDiskNumbers) {
                $baselineDisk = $csvDisks | Where-Object { [string]$_.Number -eq $dataDiskNumber } | Select-Object -First 1
                if ($null -eq $baselineDisk) {
                    Add-Finding 'Volume' "source disk $dataDiskNumber" 'ERROR' 'Data volume refers to a disk missing from disks.csv'
                    continue
                }
                $diskMatch = Get-StableDiskMatch $baselineDisk $currentStorage.Disks
                if ($null -eq $diskMatch) {
                    Add-Finding 'Volume' "source disk $dataDiskNumber" 'ERROR' 'Migrated physical disk identity was not found on destination'
                    continue
                }
                $currentDisk = $diskMatch.Disk
                if (-not (Test-StorageSizeMatch (Get-OptionalPropertyValue $baselineDisk 'Size' 0) (Get-OptionalPropertyValue $currentDisk 'Size' 0))) {
                    Add-Finding 'Volume' "source disk $dataDiskNumber" 'ERROR' ("Disk size differs: before={0}, after={1} bytes" -f `
                        (Get-OptionalPropertyValue $baselineDisk 'Size'), (Get-OptionalPropertyValue $currentDisk 'Size'))
                }
                $expectedStyle = [string](Get-OptionalPropertyValue $baselineDisk 'PartitionStyle')
                $currentStyle = [string](Get-OptionalPropertyValue $currentDisk 'PartitionStyle')
                if (-not [string]::IsNullOrWhiteSpace($expectedStyle) -and $currentStyle -ine $expectedStyle) {
                    Add-Finding 'Volume' "source disk $dataDiskNumber" 'ERROR' ("Partition style differs: before='{0}', after='{1}'" -f $expectedStyle, $currentStyle)
                } else {
                    Add-Finding 'Volume' "source disk $dataDiskNumber" 'OK' ("Physical disk verified by {0}; destination disk number={1}" -f `
                        $diskMatch.Method, (Get-OptionalPropertyValue $currentDisk 'Number'))
                }
                if (ConvertTo-BoolValue (Get-OptionalPropertyValue $currentDisk 'IsOffline' $false)) {
                    Add-Finding 'Volume' "source disk $dataDiskNumber" 'ERROR' 'Destination disk is offline'
                }
                if (ConvertTo-BoolValue (Get-OptionalPropertyValue $currentDisk 'IsReadOnly' $false)) {
                    Add-Finding 'Volume' "source disk $dataDiskNumber" 'WARN' 'Destination disk is read-only'
                }
            }
        } catch {
            Add-Finding 'Volume' 'inventory' 'ERROR' "Storage inventory failed: $_"
        }
    }
}

# ---------------------------------------------------------------------------
# 2. Local accounts
# ---------------------------------------------------------------------------
if ($check['LocalAccounts'] -and
    (Test-Path -LiteralPath (Join-Path $ExportFolder 'local_users.csv') -PathType Leaf) -and
    (Test-Path -LiteralPath (Join-Path $ExportFolder 'local_administrators_members.csv') -PathType Leaf)) {
    Write-Host "`n--- Checking local users and Administrators membership ---" -ForegroundColor White
    try {
        $currentLocalAccounts = Get-LocalAccountInventory
        $matchedUserSids = New-Object 'System.Collections.Generic.HashSet[string]' -ArgumentList ([StringComparer]::OrdinalIgnoreCase)
        foreach ($baselineUser in @($csvLocalUsers)) {
            $currentUser = Get-LocalUserMatch $baselineUser $currentLocalAccounts.Users
            $itemName = [string](Get-OptionalPropertyValue $baselineUser 'Name')
            if ($null -eq $currentUser) {
                Add-Finding 'LocalAccount' $itemName 'ERROR' 'Local user is missing; recreate manually with a new password (passwords are never exported)'
                continue
            }
            [void]$matchedUserSids.Add([string](Get-OptionalPropertyValue $currentUser 'SID'))
            $securityDrift = New-Object System.Collections.Generic.List[string]
            foreach ($flagName in @('Disabled','PasswordRequired','PasswordChangeable','PasswordExpires')) {
                $expectedFlag = ConvertTo-BoolValue (Get-OptionalPropertyValue $baselineUser $flagName $false)
                $currentFlag = ConvertTo-BoolValue (Get-OptionalPropertyValue $currentUser $flagName $false)
                if ($expectedFlag -ne $currentFlag) {
                    $securityDrift.Add(("{0} before={1} after={2}" -f $flagName, $expectedFlag, $currentFlag))
                }
            }
            if ($securityDrift.Count -gt 0) {
                Add-Finding 'LocalAccount' $itemName 'ERROR' ("Security flags differ: {0}" -f ($securityDrift -join '; '))
            } else {
                Add-Finding 'LocalAccount' $itemName 'OK' 'Local user present with matching security flags'
            }
            if ((ConvertTo-BoolValue (Get-OptionalPropertyValue $baselineUser 'Lockout' $false)) -ne
                (ConvertTo-BoolValue (Get-OptionalPropertyValue $currentUser 'Lockout' $false))) {
                Add-Finding 'LocalAccount' $itemName 'WARN' 'Lockout state differs (transient state; review only)'
            }
            foreach ($textProperty in @('Description','FullName')) {
                $expectedText = [string](Get-OptionalPropertyValue $baselineUser $textProperty)
                $currentText = [string](Get-OptionalPropertyValue $currentUser $textProperty)
                if ($currentText -cne $expectedText) {
                    Add-Finding 'LocalAccount' $itemName 'WARN' ("{0} differs: before='{1}', after='{2}'" -f $textProperty, $expectedText, $currentText)
                }
            }
        }
        foreach ($currentUser in @($currentLocalAccounts.Users)) {
            $currentSid = [string](Get-OptionalPropertyValue $currentUser 'SID')
            if ($matchedUserSids.Contains($currentSid)) { continue }
            $currentName = [string](Get-OptionalPropertyValue $currentUser 'Name')
            if ((Test-IsBuiltinLocalUserSid $currentSid) -or
                (ConvertTo-BoolValue (Get-OptionalPropertyValue $currentUser 'Disabled' $false))) {
                Add-Finding 'LocalAccount' $currentName 'SKIPPED' 'Additional built-in or disabled destination local user; not modified'
            } else {
                Add-Finding 'LocalAccount' $currentName 'WARN' 'Additional enabled local user exists on destination; review manually'
            }
        }

        $matchedAdministratorKeys = New-Object 'System.Collections.Generic.HashSet[string]' -ArgumentList ([StringComparer]::OrdinalIgnoreCase)
        foreach ($baselineMember in @($csvLocalAdministrators)) {
            $memberItem = [string](Get-OptionalPropertyValue $baselineMember 'AccountName')
            $currentMember = Get-AdministratorMemberMatch $baselineMember $currentLocalAccounts.Administrators
            if ($null -eq $currentMember) {
                Add-Finding 'LocalAccount' $memberItem 'ERROR' 'Expected local Administrators member is missing'
            } else {
                [void]$matchedAdministratorKeys.Add((Get-AdministratorMemberKey $currentMember))
                Add-Finding 'LocalAccount' $memberItem 'OK' 'Administrators membership present'
            }
        }
        foreach ($currentMember in @($currentLocalAccounts.Administrators)) {
            $currentKey = Get-AdministratorMemberKey $currentMember
            if ($matchedAdministratorKeys.Contains($currentKey)) { continue }
            $domain = [string](Get-OptionalPropertyValue $currentMember 'Domain')
            $name = [string](Get-OptionalPropertyValue $currentMember 'Name')
            $displayName = if ([string]::IsNullOrWhiteSpace($domain)) { $name } else { "$domain\$name" }
            Add-Finding 'LocalAccount' $displayName 'ERROR' 'Unexpected destination member has local Administrators rights; no automatic removal performed'
        }
    } catch {
        Add-Finding 'LocalAccount' 'inventory' 'ERROR' "Local account inventory failed: $_"
    }
}

