<#
.SYNOPSIS
    Validate SMB shares, NTFS ACLs, scheduled tasks and registry baselines after disk
    reattachment on W2K22. Run on the DESTINATION server after reboot with disks attached.
    READ-ONLY by default : nothing is modified unless a fix domain is explicitly enabled
    (-Fix or the interactive menu, with confirmation).

.PARAMETER ExportFolder
    Path to the folder generated by Export-FileServer-BeforeMigration.ps1
    (copy it from the old server beforehand).

.PARAMETER Checks
    Checks to run. Default : all.
    Valid : Manifest, Volumes, LocalAccounts, Shares, SharePerms, RootACLs, FolderACLs,
    Inheritance, FSRM, Tasks, Registry.

.PARAMETER Fix
    Fix domains to enable (each one is opt-in, independent, default NONE) :
      Shares      - recreate missing SMB shares (New-SmbShare)
      SharePerms  - restore missing share-level permissions (Grant/Block-SmbShareAccess)
      FolderAcls  - re-apply drifted folder DACLs from the baseline (DACL-only)
      Fsrm        - add or synchronize exported FSRM objects (never removes objects)
      Tasks       - import or replace tasks from full XML (requires -TaskInclude or -AllEligibleTasks)
      LanmanReg   - reg import the LanmanServer\Shares baseline (Server service restart needed)
      KVS         - reg import the Enterprise Vault KVS key
    The matching check is auto-enabled for each requested fix.

.PARAMETER Interactive
    Show a selection menu (checks + fixes). If any fix is selected, a confirmation
    ('FIX') is required before anything is modified.

.PARAMETER AutoRecreateShares
    Legacy alias for -Fix Shares.

.PARAMETER AutoRestoreSharePerms
    Legacy alias for -Fix SharePerms.

.PARAMETER ReportPath
    Output HTML report path. A machine-readable <name>_findings.csv is written next to it.

.PARAMETER TaskInclude
    Wildcard patterns matched against the full task identity (TaskPath + TaskName).
    Use with -Fix Tasks for a selective import. Leading backslash is optional.
    Example : -TaskInclude 'CUSTOM\*','Start_Windows_Update'.

.PARAMETER AllEligibleTasks
    Use with -Fix Tasks to import or replace every eligible non-Microsoft task.
    OS-specific Microsoft tasks and obsolete per-user SID tasks remain excluded and
    are listed individually with the exclusion reason.

.EXAMPLE
    # Read-only validation, all checks
    .\Compare-FileServer-AfterMigration.ps1 -ExportFolder C:\Migration_Export_20260612_0900

.EXAMPLE
    # Repair shares and share permissions only
    .\Compare-FileServer-AfterMigration.ps1 -ExportFolder C:\Export -Fix Shares,SharePerms

.EXAMPLE
    # Interactive selection
    .\Compare-FileServer-AfterMigration.ps1 -ExportFolder C:\Export -Interactive

.EXAMPLE
    # Restore FSRM objects without removing additional current objects
    .\Compare-FileServer-AfterMigration.ps1 -ExportFolder C:\Export -Fix Fsrm

.EXAMPLE
    # Restore only selected scheduled tasks
    .\Compare-FileServer-AfterMigration.ps1 -ExportFolder C:\Export -Fix Tasks -TaskInclude '\CUSTOM\*'

.EXAMPLE
    # Restore every eligible custom task
    .\Compare-FileServer-AfterMigration.ps1 -ExportFolder C:\Export -Fix Tasks -AllEligibleTasks
#>

