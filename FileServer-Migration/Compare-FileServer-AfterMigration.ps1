            }
            $eligibleBaselineTasks.Add($taskRow)
        }

        if ($AllEligibleTasks -or $null -eq $TaskInclude -or @($TaskInclude).Count -eq 0) {
            $baselineTasks = @($eligibleBaselineTasks)
        } else {
            $baselineTasks = @($eligibleBaselineTasks | Where-Object {
                $taskId = "$($_.TaskPath)$($_.TaskName)"
                Test-TaskIncluded $taskId $TaskInclude
            })
            foreach ($notSelectedTask in ($eligibleBaselineTasks | Where-Object {
                $taskId = "$($_.TaskPath)$($_.TaskName)"
                -not (Test-TaskIncluded $taskId $TaskInclude)
            })) {
                $notSelectedId = "$($notSelectedTask.TaskPath)$($notSelectedTask.TaskName)"
                Add-Finding "Task" $notSelectedId "SKIPPED" `
                    "Eligible custom task, but not selected by TaskInclude; no check or import performed"
            }
        }
        $currentTasks  = @(Get-ScheduledTask -ErrorAction SilentlyContinue)

        if (-not $AllEligibleTasks -and $null -ne $TaskInclude -and @($TaskInclude).Count -gt 0) {
            $taskIncludeExcludedCount = $eligibleBaselineTasks.Count - $baselineTasks.Count
            if ($taskIncludeExcludedCount -gt 0) {
                Add-Finding "Task" "TaskInclude scope" "WARN" `
                    "$taskIncludeExcludedCount eligible task(s) excluded by TaskInclude and not checked or modified"
            }
            foreach ($taskPattern in $TaskInclude) {
                $patternMatchCount = @($eligibleBaselineTasks | Where-Object {
                    Test-TaskIncluded "$($_.TaskPath)$($_.TaskName)" @($taskPattern)
                }).Count
                if ($patternMatchCount -eq 0) {
                    $patternStatus = if ($fixOn['Tasks']) { 'ERROR' } else { 'WARN' }
                    Add-Finding "Task" "TaskInclude '$taskPattern'" $patternStatus `
                        "Pattern matched no eligible task in the baseline; nothing was imported for this pattern"
                }
            }
        }

        if ($baselineTasks.Count -eq 0) {
            Add-Finding "Task" "eligible tasks" "OK" "No eligible task selected for checking or import"
        } else {
            $taskXmlAvailableCount = 0
            foreach ($taskXmlRow in $baselineTasks) {
                $taskXmlId = "$($taskXmlRow.TaskPath)$($taskXmlRow.TaskName)"
                $taskXmlPath = Get-TaskBaselineXmlPath $taskXmlRow $ExportFolder
                if (Test-Path -LiteralPath $taskXmlPath -PathType Leaf) {
                    $taskXmlAvailableCount++
                } else {
                    Add-Finding "Task" $taskXmlId "ERROR" "Full XML definition is missing : $taskXmlPath"
                }
            }
            if ($taskXmlAvailableCount -eq $baselineTasks.Count) {
                Add-Finding "Task" "full XML definitions" "OK" `
                    "$taskXmlAvailableCount selected task XML file(s) available (actions, triggers, settings and principals)"
            }
        }

        foreach ($bt in $baselineTasks) {
            $taskId = "$($bt.TaskPath)$($bt.TaskName)"
            $cur = $currentTasks | Where-Object { $_.TaskName -eq $bt.TaskName -and $_.TaskPath -eq $bt.TaskPath }
            if ($cur) {
                $taskDrift = @(Get-TaskMainConfigurationDrift $bt $cur)
                if ($taskDrift.Count -eq 0) {
                    Add-Finding "Task" $taskId "OK" `
                        "Task present with exported principal, enabled state, actions and trigger types"
                } else {
                    if ($fixOn['Tasks']) {
                        $xmlFile = Get-TaskBaselineXmlPath $bt $ExportFolder
                        if (Test-Path -LiteralPath $xmlFile -PathType Leaf) {
                            try {
                                Register-ScheduledTask -TaskName $bt.TaskName -TaskPath $bt.TaskPath `
                                    -Xml (Get-Content -LiteralPath $xmlFile -Raw) -Force -ErrorAction Stop | Out-Null
                                $verifyTask = Get-ScheduledTask -TaskName $bt.TaskName -TaskPath $bt.TaskPath -ErrorAction Stop
                                $verifyDrift = @(Get-TaskMainConfigurationDrift $bt $verifyTask)
                                if ($verifyDrift.Count -gt 0) {
                                    throw "post-import verification differs : $($verifyDrift -join '; ')"
                                }
                                Add-Finding "Task" $taskId "FIXED" `
                                    "Existing task replaced from $($xmlFile | Split-Path -Leaf) and verified"
                            } catch {
                                Add-Finding "Task" $taskId "ERROR" "Replace or verification failed : $_"
                            }
                        } else {
                            Add-Finding "Task" $taskId "ERROR" "Configuration differs and XML not found : $xmlFile"
                        }
                    } else {
                        Add-Finding "Task" $taskId "ERROR" ("Task configuration differs : {0}" -f ($taskDrift -join '; '))
                    }
                }
            } else {
                if ($fixOn['Tasks']) {
                    $xmlFile = Get-TaskBaselineXmlPath $bt $ExportFolder
                    if (Test-Path -LiteralPath $xmlFile -PathType Leaf) {
                        try {
                            Register-ScheduledTask -TaskName $bt.TaskName -TaskPath $bt.TaskPath `
                                -Xml (Get-Content -LiteralPath $xmlFile -Raw) -Force -ErrorAction Stop | Out-Null
                            $verifyTask = Get-ScheduledTask -TaskName $bt.TaskName -TaskPath $bt.TaskPath -ErrorAction Stop
                            $verifyDrift = @(Get-TaskMainConfigurationDrift $bt $verifyTask)
                            if ($verifyDrift.Count -gt 0) {
                                throw "post-import verification differs : $($verifyDrift -join '; ')"
                            }
                            Add-Finding "Task" $taskId "FIXED" `
                                "Task imported from $($xmlFile | Split-Path -Leaf) and verified"
                        } catch {
                            Add-Finding "Task" $taskId "ERROR" `
                                "Import or verification failed (check principal/password and XML) : $_"
                        }
                    } else {
                        Add-Finding "Task" $taskId "ERROR" "Task missing and XML not found : $xmlFile"
                    }
                } else {
                    Add-Finding "Task" $taskId "ERROR" "Task missing on this server"
                }
            }
        }
    }
