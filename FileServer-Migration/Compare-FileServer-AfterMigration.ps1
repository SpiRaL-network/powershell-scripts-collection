if ($check['LocalAccounts']) {
    $localAccountBaselineExpected = $false
    if ($null -ne $exportMetadata) {
        $selectedStepText = [string](Get-OptionalPropertyValue $exportMetadata 'SelectedSteps')
        $schemaText = [string](Get-OptionalPropertyValue $exportMetadata 'SchemaVersion')
        $schemaVersionValue = New-Object System.Version -ArgumentList 0,0
        try { $schemaVersionValue = [System.Version]::Parse($schemaText) } catch { }
        $localAccountBaselineExpected = ($selectedStepText -match '(^|,)\s*LocalAccounts\s*(,|$)' -or
            $schemaVersionValue -ge ([System.Version]::Parse('2.5')))
    }
    $missingLocalAccountArtifacts = @()
    foreach ($localArtifact in @('local_users.csv','local_administrators_members.csv')) {
        if (-not (Test-Path -LiteralPath (Join-Path $ExportFolder $localArtifact) -PathType Leaf)) {
            $missingLocalAccountArtifacts += $localArtifact
