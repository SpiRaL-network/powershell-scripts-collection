# FileSystemRights.ToString() renders ACEs carrying generic rights (GENERIC_READ etc.)
# as a raw negative number (e.g. -536805376). Decode those bits for display only -
# comparisons always use the raw string from the baseline CSV.
function Format-FsRights {
    param([string]$Rights)
    $num = [Int64]0
    if (-not [Int64]::TryParse($Rights, [ref]$num)) { return $Rights }
    $mask = [Int64]($num -band 0xFFFFFFFFL)
    $names = New-Object System.Collections.ArrayList
    if ($mask -band 0x10000000L) { [void]$names.Add('GenericAll') }
    if ($mask -band 0x20000000L) { [void]$names.Add('GenericExecute') }
    if ($mask -band 0x40000000L) { [void]$names.Add('GenericWrite') }
    if ($mask -band 0x80000000L) { [void]$names.Add('GenericRead') }
    $std = $mask -band 0x0FFFFFFFL
    if ($std -ne 0) {
        [void]$names.Add(([System.Security.AccessControl.FileSystemRights][int]$std).ToString())
    }
    if ($names.Count -eq 0) { return $Rights }
    return ('{0} (0x{1:X8})' -f ($names -join ', '), $mask)
}

