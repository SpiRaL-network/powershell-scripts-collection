if ($check['Manifest']) {
    $manifestPath = "$ExportFolder\manifest.csv"
    if (Test-Path $manifestPath) {
        Write-Host "--- Verifying export integrity (SHA256 manifest) ---" -ForegroundColor White
        $mOk = 0; $mBad = 0
        $exportBase = [System.IO.Path]::GetFullPath($ExportFolder).TrimEnd('\') + '\'
        $manifestExpectedPaths = New-Object 'System.Collections.Generic.HashSet[string]' -ArgumentList ([StringComparer]::OrdinalIgnoreCase)
        try {
            Import-Csv $manifestPath -Encoding UTF8 | ForEach-Object {
                $m = $_
                $p = $null
                try { $p = [System.IO.Path]::GetFullPath((Join-Path $ExportFolder $m.RelativePath)) } catch { }
                if ($null -eq $p -or -not $p.StartsWith($exportBase, [StringComparison]::OrdinalIgnoreCase)) {
                    $mBad++
                    Add-Finding "Manifest" $m.RelativePath "ERROR" "Invalid relative path in manifest"
                    return
                }
                $normalizedRelative = $p.Substring($exportBase.Length)
                if (-not $manifestExpectedPaths.Add($normalizedRelative)) {
                    $mBad++
                    Add-Finding "Manifest" $m.RelativePath "ERROR" "Duplicate path in manifest"
                    return
                }
                if (-not (Test-Path -LiteralPath $p -PathType Leaf)) {
                    $mBad++
                    Add-Finding "Manifest" $m.RelativePath "ERROR" "File missing from export folder"
                    return
                }
                try {
                    $fileInfo = Get-Item -LiteralPath $p -ErrorAction Stop
                    $h = (Get-FileHash -LiteralPath $p -Algorithm SHA256 -ErrorAction Stop).Hash
                    if ($h -ne $m.SHA256 -or [Int64]$fileInfo.Length -ne [Int64]$m.Length) {
                        $mBad++
                        Add-Finding "Manifest" $m.RelativePath "ERROR" "SHA256 or length mismatch - file corrupted during copy?"
                    } else {
                        $mOk++
                    }
                } catch {
                    $mBad++
                    Add-Finding "Manifest" $m.RelativePath "ERROR" "Integrity check failed : $_"
                }
            }
        } catch {
            $mBad++
            Add-Finding "Manifest" "manifest.csv" "ERROR" "Manifest cannot be read : $_"
        }
        $currentReportFull = [System.IO.Path]::GetFullPath($ReportPath)
        $currentFindingsFull = [System.IO.Path]::GetFullPath((($ReportPath -replace '\.html?$', '') + '_findings.csv'))
        foreach ($file in (Get-ChildItem -LiteralPath $ExportFolder -Recurse -File -ErrorAction SilentlyContinue)) {
            if ($file.Name -eq 'manifest.csv' -or $file.Name -eq 'summary.txt') { continue }
            if ($file.FullName -ieq $currentReportFull -or $file.FullName -ieq $currentFindingsFull) { continue }
            $fileFull = [System.IO.Path]::GetFullPath($file.FullName)
            if (-not $fileFull.StartsWith($exportBase, [StringComparison]::OrdinalIgnoreCase)) {
                $mBad++
                Add-Finding "Manifest" $file.Name "ERROR" "Resolved file path is outside the export folder"
                continue
            }
            $relative = $fileFull.Substring($exportBase.Length)
            if (-not $manifestExpectedPaths.Contains($relative)) {
                $mBad++
                Add-Finding "Manifest" $relative "ERROR" "Unexpected file is not covered by manifest"
            }
        }
        if ($mBad -eq 0 -and $mOk -gt 0) {
            $manifestVerified = $true
            Add-Finding "Manifest" "export folder" "OK" "$mOk files verified (SHA256)"
        } elseif ($mOk -eq 0) {
            $manifestFailureReason = 'manifest contains no verified file'
            Add-Finding "Manifest" "manifest.csv" "ERROR" "Manifest contains no verified file"
        } else {
            $manifestFailureReason = "$mBad integrity error(s)"
        }
    } else {
        Add-Finding "Manifest" "manifest.csv" "WARN" "No manifest in export folder - integrity not verified"
        $manifestFailureReason = 'manifest.csv is missing'
    }
}

