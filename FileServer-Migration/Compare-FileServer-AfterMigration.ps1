                            if (-not [string]::IsNullOrWhiteSpace($mappedTemplate) -and
                                (Get-FsrmFileScreenTemplate -Name $mappedTemplate -ErrorAction SilentlyContinue)) {
                                New-FsrmFileScreen -Path $row.Path -Template $mappedTemplate -Active:$active -ErrorAction Stop | Out-Null
                            } else {
                                New-FsrmFileScreen -Path $row.Path -IncludeGroup $groups -Active:$active -ErrorAction Stop | Out-Null
                            }
                            $verifyScreen = Get-FsrmFileScreen -Path $row.Path -ErrorAction Stop
                            $verifyScreenDrift = @(Get-FsrmAppliedScreenDrift $verifyScreen $active $groups $mappedTemplate)
                            if ($verifyScreenDrift.Count -gt 0) {
                                throw "post-fix verification failed : $($verifyScreenDrift -join '; ')"
                            }
                            Add-Finding "FSRM" "Screen $($row.Path)" "FIXED" "Created from baseline and verified"
                        } catch { Add-Finding "FSRM" "Screen $($row.Path)" "ERROR" "Create failed : $_" }
                    } else { Add-Finding "FSRM" "Screen $($row.Path)" "ERROR" "Missing" }
                } else {
                    $screenDriftDetail = @(Get-FsrmAppliedScreenDrift $cur $active $groups $mappedTemplate)
                    $screenDrift = ($screenDriftDetail.Count -gt 0)
                    $resetFromTemplate = ($fixOn['Fsrm'] -and $nativeStValid -and
                        (ConvertTo-BoolValue $row.MatchesTemplate) -and
                        -not [string]::IsNullOrWhiteSpace($mappedTemplate) -and
                        (Get-FsrmFileScreenTemplate -Name $mappedTemplate -ErrorAction SilentlyContinue))
                    if ($resetFromTemplate) {
                        try {
                            Reset-FsrmFileScreen -Path $row.Path -Template $mappedTemplate -ErrorAction Stop | Out-Null
                            $verifyScreen = Get-FsrmFileScreen -Path $row.Path -ErrorAction Stop
                            $verifyScreenDrift = @(Get-FsrmAppliedScreenDrift $verifyScreen $active $groups $mappedTemplate)
                            if ($verifyScreenDrift.Count -gt 0) {
                                throw "post-fix verification failed : $($verifyScreenDrift -join '; ')"
                            }
                            Add-Finding "FSRM" "Screen $($row.Path)" "FIXED" `
                                "Reset from template '$mappedTemplate'; notification actions restored and main properties verified"
                        } catch { Add-Finding "FSRM" "Screen $($row.Path)" "ERROR" "Template reset failed : $_" }
                    } elseif ($screenDrift) {
                        if ($fixOn['Fsrm']) {
                            try {
                                Set-FsrmFileScreen -Path $row.Path -IncludeGroup $groups -Active:$active -ErrorAction Stop | Out-Null
                                $verifyScreen = Get-FsrmFileScreen -Path $row.Path -ErrorAction Stop
                                $verifyScreenDrift = @(Get-FsrmAppliedScreenDrift $verifyScreen $active $groups $mappedTemplate)
                                if ($verifyScreenDrift.Count -gt 0) {
                                    throw "post-fix verification failed : $($verifyScreenDrift -join '; ')"
                                }
                                Add-Finding "FSRM" "Screen $($row.Path)" "FIXED" "Main properties synchronized and verified"
                            } catch { Add-Finding "FSRM" "Screen $($row.Path)" "ERROR" "Update failed : $_" }
                        } else { Add-Finding "FSRM" "Screen $($row.Path)" "ERROR" ($screenDriftDetail -join '; ') }
                    } else {
                        Add-Finding "FSRM" "Screen $($row.Path)" "OK" "Present with matching template and main properties"
                    }
                }
            }
            foreach ($extraScreen in @(Get-FsrmFileScreen -ErrorAction SilentlyContinue)) {
                if (-not $baselineFsrmScreenPaths.ContainsKey([string]$extraScreen.Path)) {
                    Add-Finding "FSRM" "Screen $($extraScreen.Path)" "SKIPPED" `
                        "Present only on destination; retained because FSRM fixes never remove additional objects"
                }
            }
            if ($nativeStValid -and $directAppliedScreenCount -gt 0) {
                Add-Finding "FSRM" "direct file screen notifications" "WARN" `
                    "$directAppliedScreenCount applied screen(s) did not match a template at export; direct notification actions require manual review"
            }
        }

        if (Test-Path -LiteralPath $qaPath -PathType Leaf) {
            $directAppliedQuotaCount = 0
            Import-Csv $qaPath -Encoding UTF8 | ForEach-Object {
                $row = $_
                $baselineFsrmQuotaPaths[[string]$row.Path] = $true
                if (-not (ConvertTo-BoolValue $row.MatchesTemplate)) { $directAppliedQuotaCount++ }
                $soft = ConvertTo-BoolValue $row.SoftLimit
                $mappedTemplate = [string]$row.Template
                if ($fsrmQuotaTemplateNameMap.ContainsKey($mappedTemplate)) {
                    $mappedTemplate = $fsrmQuotaTemplateNameMap[$mappedTemplate]
                }
                $cur = Get-FsrmQuota -Path $row.Path -ErrorAction SilentlyContinue
                if ($null -eq $cur) {
                    if ($fixOn['Fsrm']) {
                        try {
                            if (-not [string]::IsNullOrWhiteSpace($mappedTemplate) -and
                                (Get-FsrmQuotaTemplate -Name $mappedTemplate -ErrorAction SilentlyContinue)) {
                                New-FsrmQuota -Path $row.Path -Template $mappedTemplate -SoftLimit:$soft -ErrorAction Stop | Out-Null
                            } else {
                                New-FsrmQuota -Path $row.Path -Size ([UInt64]$row.Size) -SoftLimit:$soft -ErrorAction Stop | Out-Null
                            }
                            $verifyQuota = Get-FsrmQuota -Path $row.Path -ErrorAction Stop
                            $verifyQuotaDrift = @(Get-FsrmAppliedQuotaDrift $verifyQuota $row $mappedTemplate)
                            if ($verifyQuotaDrift.Count -gt 0) {
                                throw "post-fix verification failed : $($verifyQuotaDrift -join '; ')"
                            }
                            Add-Finding "FSRM" "Quota $($row.Path)" "FIXED" "Created from baseline and verified"
                        } catch { Add-Finding "FSRM" "Quota $($row.Path)" "ERROR" "Create failed : $_" }
                    } else { Add-Finding "FSRM" "Quota $($row.Path)" "ERROR" "Missing" }
                } else {
                    $quotaDriftDetail = @(Get-FsrmAppliedQuotaDrift $cur $row $mappedTemplate)
                    $quotaDrift = ($quotaDriftDetail.Count -gt 0)
                    $resetFromTemplate = ($fixOn['Fsrm'] -and $nativeQtValid -and
                        (ConvertTo-BoolValue $row.MatchesTemplate) -and
                        -not [string]::IsNullOrWhiteSpace($mappedTemplate) -and
                        (Get-FsrmQuotaTemplate -Name $mappedTemplate -ErrorAction SilentlyContinue))
                    if ($resetFromTemplate) {
                        try {
                            Reset-FsrmQuota -Path $row.Path -Template $mappedTemplate -ErrorAction Stop | Out-Null
                            $verifyQuota = Get-FsrmQuota -Path $row.Path -ErrorAction Stop
                            $verifyQuotaDrift = @(Get-FsrmAppliedQuotaDrift $verifyQuota $row $mappedTemplate)
                            if ($verifyQuotaDrift.Count -gt 0) {
                                throw "post-fix verification failed : $($verifyQuotaDrift -join '; ')"
                            }
                            Add-Finding "FSRM" "Quota $($row.Path)" "FIXED" `
                                "Reset from template '$mappedTemplate'; threshold actions restored and main properties verified"
                        } catch { Add-Finding "FSRM" "Quota $($row.Path)" "ERROR" "Template reset failed : $_" }
                    } elseif ($quotaDrift) {
                        if ($fixOn['Fsrm']) {
                            try {
                                Set-FsrmQuota -Path $row.Path -Size ([UInt64]$row.Size) -SoftLimit:$soft -ErrorAction Stop | Out-Null
                                $verifyQuota = Get-FsrmQuota -Path $row.Path -ErrorAction Stop
                                $verifyQuotaDrift = @(Get-FsrmAppliedQuotaDrift $verifyQuota $row $mappedTemplate)
                                if ($verifyQuotaDrift.Count -gt 0) {
                                    throw "post-fix verification failed : $($verifyQuotaDrift -join '; ')"
                                }
                                Add-Finding "FSRM" "Quota $($row.Path)" "FIXED" "Size and limit type synchronized and verified"
                            } catch { Add-Finding "FSRM" "Quota $($row.Path)" "ERROR" "Update failed : $_" }
                        } else { Add-Finding "FSRM" "Quota $($row.Path)" "ERROR" ($quotaDriftDetail -join '; ') }
                    } else {
                        Add-Finding "FSRM" "Quota $($row.Path)" "OK" "Present with matching template, size and limit type"
                    }
                }
            }
            foreach ($extraQuota in @(Get-FsrmQuota -ErrorAction SilentlyContinue)) {
                if (-not $baselineFsrmQuotaPaths.ContainsKey([string]$extraQuota.Path)) {
                    Add-Finding "FSRM" "Quota $($extraQuota.Path)" "SKIPPED" `
                        "Present only on destination; retained because FSRM fixes never remove additional objects"
                }
            }
            if ($nativeQtValid -and $directAppliedQuotaCount -gt 0) {
                Add-Finding "FSRM" "direct quota threshold actions" "WARN" `
                    "$directAppliedQuotaCount applied quota(s) did not match a template at export; direct threshold actions require manual review"
            }
        }
    }
}

