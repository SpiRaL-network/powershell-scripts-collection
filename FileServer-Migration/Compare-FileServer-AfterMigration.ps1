function ConvertFrom-SemicolonList {
    param([string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value)) { return @() }
    return @($Value -split ';\s*' | Where-Object { -not [string]::IsNullOrWhiteSpace($_) })
}

function Test-StringSetEqual {
    param($Expected, $Current)
    $left  = @($Expected | ForEach-Object { [string]$_ } | Sort-Object)
    $right = @($Current  | ForEach-Object { [string]$_ } | Sort-Object)
    return (@(Compare-Object -ReferenceObject $left -DifferenceObject $right).Count -eq 0)
}

