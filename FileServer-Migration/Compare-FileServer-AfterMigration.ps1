function Get-TaskMainConfigurationDrift {
    param($TaskRow, $CurrentTask)
    $drift = New-Object 'System.Collections.Generic.List[string]'
    $currentActions = foreach ($action in $CurrentTask.Actions) {
        if ($action.PSObject.Properties.Name -contains 'Execute') {
            "$($action.Execute) $($action.Arguments)".Trim()
        } else {
            $action.GetType().Name
        }
    }
    $currentTriggers = foreach ($trigger in $CurrentTask.Triggers) { $trigger.GetType().Name }
    $baselineAuthorSid = if ($TaskRow.PSObject.Properties.Name -contains 'AuthorSid' -and
        -not [string]::IsNullOrWhiteSpace($TaskRow.AuthorSid)) {
        $TaskRow.AuthorSid
    } else {
        ConvertTo-IdentitySidKey $TaskRow.Author
    }
    $currentAuthorSid = ConvertTo-IdentitySidKey $CurrentTask.Principal.UserId
    if ($currentAuthorSid -ne $baselineAuthorSid) {
        $drift.Add("principal SID before='$($TaskRow.Author)' [$baselineAuthorSid] after='$($CurrentTask.Principal.UserId)' [$currentAuthorSid]")
    }
    if ([string]$CurrentTask.Principal.RunLevel -ne [string]$TaskRow.RunLevel) {
        $drift.Add("run level before='$($TaskRow.RunLevel)' after='$($CurrentTask.Principal.RunLevel)'")
    }
    if ([string]$CurrentTask.Principal.LogonType -ne [string]$TaskRow.LogonType) {
        $drift.Add("logon type before='$($TaskRow.LogonType)' after='$($CurrentTask.Principal.LogonType)'")
    }
    if (($currentActions -join '; ') -ne [string]$TaskRow.Actions) { $drift.Add('actions differ') }
    if (($currentTriggers -join '; ') -ne [string]$TaskRow.Triggers) { $drift.Add('trigger types differ') }
    $baselineDisabled = ([string]$TaskRow.State -eq 'Disabled')
    $currentDisabled = ([string]$CurrentTask.State -eq 'Disabled')
    if ($currentDisabled -ne $baselineDisabled) {
        $drift.Add("enabled state before='$($TaskRow.State)' after='$($CurrentTask.State)'")
    }
    return @($drift)
}

