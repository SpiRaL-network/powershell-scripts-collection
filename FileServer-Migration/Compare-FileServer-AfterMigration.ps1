function Show-CompareMenu {
    $selChecks = @{}
    $selFixes  = @{}
    foreach ($id in $CHECK_IDS) { $selChecks[$id] = $true }
    foreach ($id in $FIX_IDS)   { $selFixes[$id]  = $false }

    while ($true) {
        Clear-Host
        Write-Host ""
        Write-Host "  =====================================================" -ForegroundColor Cyan
        Write-Host "    Post-migration validation  -  selection" -ForegroundColor Cyan
        Write-Host "  =====================================================" -ForegroundColor Cyan
        Write-Host ""
        Write-Host "  CHECKS (read-only)" -ForegroundColor White

        $i = 1
        foreach ($id in $CHECK_IDS) {
            $mark  = if ($selChecks[$id]) { '[X]' } else { '[ ]' }
            $color = if ($selChecks[$id]) { 'Green' } else { 'DarkGray' }
            Write-Host ("  {0} {1,2}  {2}" -f $mark, $i, $CHECK_LABELS[$id]) -ForegroundColor $color
            $i++
        }

        Write-Host ""
        Write-Host "  FIXES (MODIFY this server - default OFF)" -ForegroundColor Yellow
        foreach ($id in $FIX_IDS) {
            $mark  = if ($selFixes[$id]) { '[X]' } else { '[ ]' }
            $color = if ($selFixes[$id]) { 'Yellow' } else { 'DarkGray' }
            Write-Host ("  {0} {1,2}  {2}" -f $mark, $i, $FIX_LABELS[$id]) -ForegroundColor $color
            $i++
        }

        Write-Host ""
        Write-Host ("  Commands : 1-{0} toggle  |  A all checks  |  N none  |  R run" -f ($CHECK_IDS.Count + $FIX_IDS.Count)) -ForegroundColor DarkCyan
        Write-Host ""
        $choice = (Read-Host "  Choice").Trim().ToUpper()

        if ($choice -eq 'R') {
            $anyCheck = $false
            foreach ($id in $CHECK_IDS) { if ($selChecks[$id]) { $anyCheck = $true; break } }
            if (-not $anyCheck) {
                Write-Host "  No check selected. Select at least one." -ForegroundColor Red
                Start-Sleep -Seconds 2
                continue
            }
            break
        }
        elseif ($choice -eq 'A') {
            foreach ($id in $CHECK_IDS) { $selChecks[$id] = $true }
        }
        elseif ($choice -eq 'N') {
            foreach ($id in $CHECK_IDS) { $selChecks[$id] = $false }
            foreach ($id in $FIX_IDS)   { $selFixes[$id]  = $false }
        }
        else {
            $tokens = $choice -split '[,\s]+' | Where-Object { $_ -ne '' }
            foreach ($token in $tokens) {
                $n = 0
                if ([int]::TryParse($token, [ref]$n)) {
                    if ($n -ge 1 -and $n -le $CHECK_IDS.Count) {
                        $id = $CHECK_IDS[$n - 1]
                        $selChecks[$id] = -not $selChecks[$id]
                    } elseif ($n -gt $CHECK_IDS.Count -and $n -le ($CHECK_IDS.Count + $FIX_IDS.Count)) {
                        $id = $FIX_IDS[$n - 1 - $CHECK_IDS.Count]
                        $selFixes[$id] = -not $selFixes[$id]
                    }
                }
            }
        }
    }

    return @($selChecks, $selFixes)
}

