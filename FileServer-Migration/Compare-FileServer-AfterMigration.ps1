function Get-FsrmFileGroupDrift {
    param($Current, [string[]]$ExpectedInclude, [string[]]$ExpectedExclude)
    $drift = New-Object 'System.Collections.Generic.List[string]'
    if ($null -eq $Current) { $drift.Add('missing'); return @($drift) }
    if (-not (Test-StringSetEqual $ExpectedInclude @($Current.IncludePattern))) {
        $drift.Add('include patterns differ')
