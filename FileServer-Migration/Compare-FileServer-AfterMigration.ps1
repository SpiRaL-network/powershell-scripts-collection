$missingBaselineItems = New-Object 'System.Collections.Generic.HashSet[string]' -ArgumentList ([StringComparer]::OrdinalIgnoreCase)
function Add-MissingBaseline {
    param([string]$Artifact, [string]$RequiredBy)
    $key = "$RequiredBy|$Artifact"
    if ($missingBaselineItems.Add($key)) {
        Add-Finding "Baseline" $Artifact "ERROR" "Required by selected check '$RequiredBy' but missing from export"
    }
}

