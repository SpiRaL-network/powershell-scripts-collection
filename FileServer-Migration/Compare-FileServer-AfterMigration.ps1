if ($check['Shares']) {
    Write-Host "`n--- Checking SMB shares ---" -ForegroundColor White

    $currentShares = Get-SmbShare

    foreach ($s in $csvShares) {
        $cur = $currentShares | Where-Object { $_.Name -eq $s.Name }

        if (-not $cur) {
            if ($fixOn['Shares'] -and $s.Path -and (Test-Path $s.Path)) {
                try {
                    $params = @{
                        Name        = $s.Name
                        Path        = $s.Path
                        Description = $s.Description
                        ErrorAction = 'Stop'
                    }
                    if ($s.ScopeName)             { $params['ScopeName']             = $s.ScopeName }
                    if ($s.CachingMode)           { $params['CachingMode']           = $s.CachingMode }
                    if ($s.FolderEnumerationMode) { $params['FolderEnumerationMode'] = $s.FolderEnumerationMode }
                    if ($s.PSObject.Properties.Name -contains 'EncryptData') {
                        $params['EncryptData'] = ConvertTo-BoolValue $s.EncryptData
                    }
                    if ($s.PSObject.Properties.Name -contains 'ContinuouslyAvailable') {
                        $params['ContinuouslyAvailable'] = ConvertTo-BoolValue $s.ContinuouslyAvailable
                    }
                    if ([int]$s.ConcurrentUserLimit -gt 0) {
                        $params['ConcurrentUserLimit'] = [int]$s.ConcurrentUserLimit
                    }
                    New-SmbShare @params | Out-Null
                    $created = Get-SmbShare -Name $s.Name -ErrorAction Stop
                    $postCreateDrift = @(Get-ShareDrift $s $created)
                    if ($postCreateDrift.Count -eq 0) {
                        Add-Finding "Share" $s.Name "FIXED" "Share recreated with exported properties -> $($s.Path)"
                    } else {
                        Add-Finding "Share" $s.Name "ERROR" ("Share recreated but properties differ : {0}" -f ($postCreateDrift -join '; '))
                    }
                } catch {
                    Add-Finding "Share" $s.Name "ERROR" "Recreation failed : $_"
                }
            } else {
                Add-Finding "Share" $s.Name "ERROR" "Share missing on new server (path=$($s.Path))"
            }
        } else {
            $shareDrift = @(Get-ShareDrift $s $cur)
            if ($shareDrift.Count -gt 0) {
                Add-Finding "Share" $s.Name "ERROR" ("Share properties differ : {0}" -f ($shareDrift -join '; '))
            } else {
                Add-Finding "Share" $s.Name "OK" "Share present with exported properties -> $($cur.Path)"
            }
        }
    }

    # Shares present on new server but absent in export
    $currentShares = Get-SmbShare
    foreach ($cur in $currentShares) {
        if ($cur.Special) { continue }
        $old = $csvShares | Where-Object { $_.Name -eq $cur.Name }
        if (-not $old) {
            Add-Finding "Share" $cur.Name "WARN" "Share not in source export (new or unexpected)"
        }
    }
}

