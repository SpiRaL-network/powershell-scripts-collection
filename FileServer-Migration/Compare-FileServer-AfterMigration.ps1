function Get-TaskPermanentSkipReason {
    param($TaskRow)
    if ([string]$TaskRow.TaskPath -like '\Microsoft\*') {
        return 'Microsoft/Windows OS task: not imported because its definition is specific to the destination OS version'
    }
    if (Test-IsGeneratedUserTask $TaskRow) {
        return 'Obsolete per-user SID task (WPD or Start Menu cache): not imported after migration'
    }
    if ([string]$TaskRow.TaskPath -eq '\' -and [string]$TaskRow.TaskName -ieq 'azcmagent') {
        return 'Azure Connected Machine Agent managed task: repair or reinstall the agent instead of importing a standalone scheduled task'
    }
    return ''
}

function Test-TaskIncluded {
    param([string]$TaskId, [string[]]$Patterns)
    if ($null -eq $Patterns -or @($Patterns).Count -eq 0) { return $true }
    foreach ($pattern in $Patterns) {
        $normalizedPattern = ([string]$pattern).Trim()
        if ([string]::IsNullOrWhiteSpace($normalizedPattern)) { continue }
        if (-not $normalizedPattern.StartsWith('\')) { $normalizedPattern = '\' + $normalizedPattern }
        if ($TaskId -like $normalizedPattern) { return $true }
    }
    return $false
}

# Breadth-first directory traversal, PS4-compatible (no Get-ChildItem -Depth).
# Only used by the Inheritance fallback when the baseline CSV is missing.
function Get-DirsBFS {
    param([string]$Root, [int]$MaxDepth)
    $queue = New-Object System.Collections.Queue
    $queue.Enqueue([PSCustomObject]@{ Path = $Root; Depth = 0 })
    while ($queue.Count -gt 0) {
        $item = $queue.Dequeue()
        $item
        $descend = ($MaxDepth -lt 0 -or $item.Depth -lt $MaxDepth)
        if ($descend -and $item.Depth -gt 0) {
            try {
                $attrs = [System.IO.File]::GetAttributes($item.Path)
                if (($attrs -band [System.IO.FileAttributes]::ReparsePoint) -ne 0) {
                    $descend = $false
                }
            } catch {
                $descend = $false
            }
        }
        if ($descend) {
            try {
                foreach ($childPath in [System.IO.Directory]::EnumerateDirectories($item.Path)) {
                    $queue.Enqueue([PSCustomObject]@{ Path = $childPath; Depth = ($item.Depth + 1) })
                }
            } catch {
                Write-Warning ("Directory enumeration failed : {0} : {1}" -f $item.Path, $_.Exception.Message)
            }
        }
    }
}

function ConvertTo-BoolValue {
    param($Value)
    if ($Value -is [bool]) { return [bool]$Value }
    return ([string]$Value -eq 'True')
}

function Get-OptionalPropertyValue {
    param($Object, [string]$Name, $DefaultValue = '')
    if ($null -eq $Object) { return $DefaultValue }
    $property = $Object.PSObject.Properties[$Name]
    if ($null -eq $property -or $null -eq $property.Value) { return $DefaultValue }
    return $property.Value
}

function ConvertTo-StorageIdentityKey {
    param($Value)
    if ($null -eq $Value) { return '' }
    return (([string]$Value).Trim().ToUpperInvariant() -replace '[\s{}]', '')
}

function Test-StorageSizeMatch {
    param($Expected, $Current)
    $expectedSize = [UInt64]$Expected
    $currentSize = [UInt64]$Current
    $difference = if ($expectedSize -gt $currentSize) {
        $expectedSize - $currentSize
    } else {
        $currentSize - $expectedSize
    }
    $tolerance = [UInt64][math]::Max(1MB, [double]$expectedSize * 0.001)
    return ($difference -le $tolerance)
}

function Get-StorageInventory {
    $volumes = @(Get-Volume -ErrorAction Stop)
    $partitions = @(Get-Partition -ErrorAction Stop)
    $disks = @(Get-Disk -ErrorAction Stop)

    $volumeRows = foreach ($volume in $volumes) {
        $driveLetter = [string](Get-OptionalPropertyValue $volume 'DriveLetter')
        $volumeUniqueId = [string](Get-OptionalPropertyValue $volume 'UniqueId')
        $volumePath = [string](Get-OptionalPropertyValue $volume 'Path')
        $partition = $null
        if (-not [string]::IsNullOrWhiteSpace($driveLetter)) {
            $partition = $partitions | Where-Object {
                [string](Get-OptionalPropertyValue $_ 'DriveLetter') -ieq $driveLetter
            } | Select-Object -First 1
        }
        if ($null -eq $partition -and
            (-not [string]::IsNullOrWhiteSpace($volumeUniqueId) -or
             -not [string]::IsNullOrWhiteSpace($volumePath))) {
            $partition = $partitions | Where-Object {
                $accessPaths = @(Get-OptionalPropertyValue $_ 'AccessPaths' @())
                ($accessPaths -icontains $volumeUniqueId) -or ($accessPaths -icontains $volumePath)
            } | Select-Object -First 1
        }
        $disk = $null
        if ($null -ne $partition) {
            $partitionDiskNumber = Get-OptionalPropertyValue $partition 'DiskNumber' -1
            $disk = $disks | Where-Object {
                [int](Get-OptionalPropertyValue $_ 'Number' -2) -eq [int]$partitionDiskNumber
            } | Select-Object -First 1
        }
        $systemDriveLetter = ([string]$env:SystemDrive).TrimEnd([char[]]@(':','\'))
        [PSCustomObject]@{
            DriveLetter       = $driveLetter
            FileSystemLabel   = [string](Get-OptionalPropertyValue $volume 'FileSystemLabel')
            FileSystem        = [string](Get-OptionalPropertyValue $volume 'FileSystem')
            DriveType         = [string](Get-OptionalPropertyValue $volume 'DriveType')
            HealthStatus      = [string](Get-OptionalPropertyValue $volume 'HealthStatus')
            OperationalStatus = (@(Get-OptionalPropertyValue $volume 'OperationalStatus' @()) -join '; ')
            SizeRemaining     = [UInt64](Get-OptionalPropertyValue $volume 'SizeRemaining' 0)
            Size              = [UInt64](Get-OptionalPropertyValue $volume 'Size' 0)
            IsDataDisk        = (-not [string]::IsNullOrWhiteSpace($driveLetter) -and $driveLetter -ine $systemDriveLetter)
            VolumeUniqueId    = $volumeUniqueId
            VolumePath        = $volumePath
            DiskNumber        = Get-OptionalPropertyValue $partition 'DiskNumber' ''
            PartitionNumber   = Get-OptionalPropertyValue $partition 'PartitionNumber' ''
            PartitionGuid     = [string](Get-OptionalPropertyValue $partition 'Guid')
            PartitionOffset   = Get-OptionalPropertyValue $partition 'Offset' ''
            PartitionSize     = Get-OptionalPropertyValue $partition 'Size' ''
            PartitionType     = [string](Get-OptionalPropertyValue $partition 'Type')
            DiskUniqueId      = [string](Get-OptionalPropertyValue $disk 'UniqueId')
            DiskSerialNumber  = [string](Get-OptionalPropertyValue $disk 'SerialNumber')
            DiskGuid          = [string](Get-OptionalPropertyValue $disk 'Guid')
            DiskSignature     = [string](Get-OptionalPropertyValue $disk 'Signature')
            DiskFriendlyName  = [string](Get-OptionalPropertyValue $disk 'FriendlyName')
            DiskBusType       = [string](Get-OptionalPropertyValue $disk 'BusType')
            DiskSize          = Get-OptionalPropertyValue $disk 'Size' ''
            DiskPartitionStyle= [string](Get-OptionalPropertyValue $disk 'PartitionStyle')
        }
    }

    $diskRows = foreach ($disk in $disks) {
        [PSCustomObject]@{
            Number            = Get-OptionalPropertyValue $disk 'Number' ''
            FriendlyName      = [string](Get-OptionalPropertyValue $disk 'FriendlyName')
            SerialNumber      = [string](Get-OptionalPropertyValue $disk 'SerialNumber')
            UniqueId          = [string](Get-OptionalPropertyValue $disk 'UniqueId')
            Guid              = [string](Get-OptionalPropertyValue $disk 'Guid')
            Signature         = [string](Get-OptionalPropertyValue $disk 'Signature')
            PartitionStyle    = [string](Get-OptionalPropertyValue $disk 'PartitionStyle')
            OperationalStatus = (@(Get-OptionalPropertyValue $disk 'OperationalStatus' @()) -join '; ')
            HealthStatus      = [string](Get-OptionalPropertyValue $disk 'HealthStatus')
            Size              = Get-OptionalPropertyValue $disk 'Size' ''
            BusType           = [string](Get-OptionalPropertyValue $disk 'BusType')
            IsBoot            = Get-OptionalPropertyValue $disk 'IsBoot' ''
            IsSystem          = Get-OptionalPropertyValue $disk 'IsSystem' ''
            IsOffline         = Get-OptionalPropertyValue $disk 'IsOffline' ''
            IsReadOnly        = Get-OptionalPropertyValue $disk 'IsReadOnly' ''
            Location          = [string](Get-OptionalPropertyValue $disk 'Location')
        }
    }
    return [PSCustomObject]@{ Volumes=@($volumeRows); Disks=@($diskRows) }
}

function Get-StableVolumeMatch {
    param($BaselineVolume, $CurrentVolumes)

    $identityTests = @(
        @('VolumeUniqueId','VolumeUniqueId'),
        @('PartitionGuid','PartitionGuid')
    )
    foreach ($identityTest in $identityTests) {
        $baselineProperty = [string](Get-OptionalPropertyValue $BaselineVolume $identityTest[0])
        if ([string]::IsNullOrWhiteSpace($baselineProperty)) { continue }
        $expectedKey = ConvertTo-StorageIdentityKey $baselineProperty
        $matches = @($CurrentVolumes | Where-Object {
            (ConvertTo-StorageIdentityKey (Get-OptionalPropertyValue $_ $identityTest[1])) -eq $expectedKey
        })
        if ($matches.Count -eq 1) {
            return [PSCustomObject]@{ Volume=$matches[0]; Method=$identityTest[0]; Stable=$true }
        }
    }

    $compoundTests = @(
        @('DiskGuid','PartitionNumber'),
        @('DiskUniqueId','PartitionOffset'),
        @('DiskSerialNumber','PartitionOffset')
    )
    foreach ($compoundTest in $compoundTests) {
        $expectedDisk = [string](Get-OptionalPropertyValue $BaselineVolume $compoundTest[0])
        $expectedPartition = [string](Get-OptionalPropertyValue $BaselineVolume $compoundTest[1])
        if ([string]::IsNullOrWhiteSpace($expectedDisk) -or
            [string]::IsNullOrWhiteSpace($expectedPartition)) { continue }
        $expectedDiskKey = ConvertTo-StorageIdentityKey $expectedDisk
        $matches = @($CurrentVolumes | Where-Object {
            (ConvertTo-StorageIdentityKey (Get-OptionalPropertyValue $_ $compoundTest[0])) -eq $expectedDiskKey -and
            [string](Get-OptionalPropertyValue $_ $compoundTest[1]) -eq $expectedPartition
        })
        if ($matches.Count -eq 1) {
            return [PSCustomObject]@{ Volume=$matches[0]; Method=($compoundTest -join '+'); Stable=$true }
        }
    }

    $expectedLabel = [string](Get-OptionalPropertyValue $BaselineVolume 'FileSystemLabel')
    $expectedSize = [string](Get-OptionalPropertyValue $BaselineVolume 'Size')
    if (-not [string]::IsNullOrWhiteSpace($expectedLabel) -and
        -not [string]::IsNullOrWhiteSpace($expectedSize)) {
        $matches = @($CurrentVolumes | Where-Object {
            [string](Get-OptionalPropertyValue $_ 'FileSystemLabel') -ieq $expectedLabel -and
            (Test-StorageSizeMatch $expectedSize (Get-OptionalPropertyValue $_ 'Size' 0))
        })
        if ($matches.Count -eq 1) {
            return [PSCustomObject]@{ Volume=$matches[0]; Method='Label+Size'; Stable=$true }
        }
    }

    $expectedLetter = [string](Get-OptionalPropertyValue $BaselineVolume 'DriveLetter')
    if (-not [string]::IsNullOrWhiteSpace($expectedLetter)) {
        $matches = @($CurrentVolumes | Where-Object {
            [string](Get-OptionalPropertyValue $_ 'DriveLetter') -ieq $expectedLetter
        })
        if ($matches.Count -eq 1) {
            return [PSCustomObject]@{ Volume=$matches[0]; Method='DriveLetterFallback'; Stable=$false }
        }
    }
    return $null
}

function Get-StableDiskMatch {
    param($BaselineDisk, $CurrentDisks)

    foreach ($propertyName in @('Guid','UniqueId','SerialNumber','Signature')) {
        $expectedValue = [string](Get-OptionalPropertyValue $BaselineDisk $propertyName)
        if ([string]::IsNullOrWhiteSpace($expectedValue) -or $expectedValue -eq '0') { continue }
        $expectedKey = ConvertTo-StorageIdentityKey $expectedValue
        $matches = @($CurrentDisks | Where-Object {
            (ConvertTo-StorageIdentityKey (Get-OptionalPropertyValue $_ $propertyName)) -eq $expectedKey
        })
        if ($matches.Count -eq 1) {
            return [PSCustomObject]@{ Disk=$matches[0]; Method=$propertyName; Stable=$true }
        }
    }
    return $null
}

function Get-LocalAccountInventory {
    $localUsers = @(Get-CimInstance -ClassName Win32_UserAccount -Filter "LocalAccount=True" -ErrorAction Stop)
    $localGroups = @(Get-CimInstance -ClassName Win32_Group -Filter "LocalAccount=True" -ErrorAction Stop)
    $administratorsGroup = $localGroups | Where-Object { [string]$_.SID -eq 'S-1-5-32-544' } | Select-Object -First 1
    if ($null -eq $administratorsGroup) { throw 'Local Administrators group (S-1-5-32-544) was not found' }
    $members = @(Get-CimAssociatedInstance -InputObject $administratorsGroup `
        -Association Win32_GroupUser -ErrorAction Stop)
    return [PSCustomObject]@{ Users=$localUsers; Administrators=$members; Group=$administratorsGroup }
}

function Test-IsBuiltinLocalUserSid {
    param([string]$Sid)
    return ($Sid -match '-(500|501|503|504)$')
}

function Get-LocalUserMatch {
    param($BaselineUser, $CurrentUsers)
    if (Test-IsBuiltinLocalUserSid ([string]$BaselineUser.SID)) {
        $rid = ([string]$BaselineUser.SID -split '-')[-1]
        return ($CurrentUsers | Where-Object { [string]$_.SID -match "-$rid$" } | Select-Object -First 1)
    }
    return ($CurrentUsers | Where-Object { [string]$_.Name -ieq [string]$BaselineUser.Name } | Select-Object -First 1)
}

function Test-IsLocalAccountObject {
    param($Account)
    $localAccountValue = Get-OptionalPropertyValue $Account 'LocalAccount' $false
    $domain = [string](Get-OptionalPropertyValue $Account 'Domain')
    return ((ConvertTo-BoolValue $localAccountValue) -or $domain -ieq $env:COMPUTERNAME)
}

function Get-AdministratorMemberKey {
    param($Member)
    $sid = [string](Get-OptionalPropertyValue $Member 'SID')
    if (-not [string]::IsNullOrWhiteSpace($sid)) { return $sid.ToUpperInvariant() }
    $domain = [string](Get-OptionalPropertyValue $Member 'Domain')
    $name = [string](Get-OptionalPropertyValue $Member 'Name')
    return ("{0}\{1}" -f $domain, $name).ToUpperInvariant()
}

function Get-AdministratorMemberMatch {
    param($BaselineMember, $CurrentMembers)
    $baselineSid = [string](Get-OptionalPropertyValue $BaselineMember 'SID')
    $baselineIsLocal = ConvertTo-BoolValue (Get-OptionalPropertyValue $BaselineMember 'IsLocal' $false)

    if ($baselineIsLocal) {
        if (Test-IsBuiltinLocalUserSid $baselineSid) {
            $rid = ($baselineSid -split '-')[-1]
            return ($CurrentMembers | Where-Object {
                (Test-IsLocalAccountObject $_) -and [string](Get-OptionalPropertyValue $_ 'SID') -match "-$rid$"
            } | Select-Object -First 1)
        }
        $baselineName = [string](Get-OptionalPropertyValue $BaselineMember 'Name')
        return ($CurrentMembers | Where-Object {
            (Test-IsLocalAccountObject $_) -and [string](Get-OptionalPropertyValue $_ 'Name') -ieq $baselineName
        } | Select-Object -First 1)
    }

    if (-not [string]::IsNullOrWhiteSpace($baselineSid)) {
        $sidMatch = $CurrentMembers | Where-Object {
            [string](Get-OptionalPropertyValue $_ 'SID') -ieq $baselineSid
        } | Select-Object -First 1
        if ($null -ne $sidMatch) { return $sidMatch }
    }
    $baselineDomain = [string](Get-OptionalPropertyValue $BaselineMember 'Domain')
    $baselineName = [string](Get-OptionalPropertyValue $BaselineMember 'Name')
    return ($CurrentMembers | Where-Object {
        [string](Get-OptionalPropertyValue $_ 'Domain') -ieq $baselineDomain -and
        [string](Get-OptionalPropertyValue $_ 'Name') -ieq $baselineName
    } | Select-Object -First 1)
}

function Test-XmlFileWellFormed {
    param([string]$Path)
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $false }
    try {
        $xmlDocument = New-Object System.Xml.XmlDocument
        $xmlDocument.Load($Path)
        return $true
    } catch {
        return $false
    }
}

function Invoke-FsrmNativeImport {
    param(
        [string]$CommandName,
        [string]$ObjectType,
        [string]$SelectionName,
        [string]$SelectionValue,
        [string]$XmlPath
    )

    if (-not (Test-XmlFileWellFormed $XmlPath)) {
        throw "native XML baseline is missing or invalid : $XmlPath"
    }
    $command = Get-Command -Name $CommandName -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($null -eq $command) { throw "$CommandName is not available" }

    $nativeOutput = & $command $ObjectType 'import' ("/file:{0}" -f $XmlPath) `
        ("/{0}:{1}" -f $SelectionName, $SelectionValue) 2>&1
    if ($command.CommandType -eq [System.Management.Automation.CommandTypes]::Application -and
        $LASTEXITCODE -ne 0) {
        throw "$CommandName exited with code $LASTEXITCODE : $($nativeOutput -join ' ')"
    }
}

function ConvertTo-AsciiIdentityKey {
    param([string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value)) { return '' }
    $decomposed = $Value.Normalize([System.Text.NormalizationForm]::FormD)
    $builder = New-Object System.Text.StringBuilder
    foreach ($character in $decomposed.ToCharArray()) {
        $category = [System.Globalization.CharUnicodeInfo]::GetUnicodeCategory($character)
        if ($category -ne [System.Globalization.UnicodeCategory]::NonSpacingMark) {
            [void]$builder.Append($character)
        }
    }
    return $builder.ToString().Normalize([System.Text.NormalizationForm]::FormC).ToUpperInvariant()
}

